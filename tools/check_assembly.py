        f"assembled by crushing it — a failure no strength check reported.",
        f"{len(slow)} ends need more than 0.20 mm of embedment to reach their saturated "
        f"bearing; the deepest is {max((e['embedToSatMm'] or 0) for e in ends):.2f} mm.",
