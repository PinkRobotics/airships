def elastic_slack(g, vc, prm, demand, demand_family):
    """A2 — can a closing member simply be sprung in? No, by four orders of magnitude.

    Assemble K = sum (EA/L) b b^T over the pin-jointed truss, then for each member remove its
    own contribution and solve the reduced system for the gap its endpoints open under a unit
    self-equilibrated pair. The model is a LOWER bound on stiffness — real sockets carry moment
    — so the real force is higher than what this prints.

    `demand` IS PASSED IN AND IS THE SMALLEST OF THE SIX FAMILY DEMANDS, not gen_nodes'
    --demand-n. The tolerance below has to hold for every member, so it is set by the member
    with the least room — and reading the generator's own 3372 N parameter here quoted a number
    that is neither the octet's derived demand nor the tightest one, on the same article where
    P12 exists to stop one number standing in for six.
    """
    nodes, members = g["nodes"], g["members"]
    E_mod = vc.MATERIALS["T700_LAM"]["E"] / 1e6            # N/mm2
    A = math.pi * ((prm["pipe_od"] / 2.0) ** 2 - (prm["pipe_id"] / 2.0) ** 2)
    V = len(nodes)
    K = np.zeros((3 * V, 3 * V))
    bs = []
    for a, b, _ in members:
        pa = g["pos"][a]
        pb = g["pos"][b]
        d = pb - pa
        L = float(np.linalg.norm(d))
        un = d / L
        bv = np.zeros(3 * V)
        ia, ib = g["index"][a], g["index"][b]
        bv[3 * ia:3 * ia + 3] = -un
        bv[3 * ib:3 * ib + 3] = un
        k = E_mod * A / L
        bs.append((bv, k, L))
        K += k * np.outer(bv, bv)
    flex = []
    for bv, k, L in bs:
        Km = K - k * np.outer(bv, bv)
        flex.append(float(bv @ (np.linalg.pinv(Km, rcond=1e-10) @ bv)))
    flex = np.array(flex)
    hand = 200.0
    lines = [
        f"gap-opening flexibility {flex.min():.4e} to {flex.max():.4e} mm/N, so opening a gap "
        f"by the full {prm['stub']:.0f} mm stub costs {prm['stub'] / flex.max():,.0f} to "
        f"{prm['stub'] / flex.min():,.0f} N. {hand:.0f} N of hand force opens "
        f"{hand * flex.min():.4f} to {hand * flex.max():.4f} mm; "
        f"{int((hand * flex > 0.1).sum())} of {len(members)} members exceed 0.1 mm on the "
        f"finished article. That is why the closing ends carry a {prm['pilot']:.0f} mm pilot "
        f"and not a shortened stub plus optimism: 'just spring it in' is the natural response "
        f"to P1 and it is wrong by four orders of magnitude. Even the pilot's own "
        f"{prm['pilot']:.0f} mm would cost {prm['pilot'] / flex.max():,.0f} N to spring, which "
        f"is why it is swung in instead. This is a pin-jointed LOWER bound on stiffness.",
    ]
    bows = []
    for L, dl in ((250.669, prm["stub"]), (HALF, prm["stub"]), (HALF, 3.0)):
        amp = math.sqrt(4.0 * L * dl / math.pi ** 2)
        strain = (prm["pipe_od"] / 2.0) * amp * math.pi ** 2 / L ** 2
        bows.append((L, dl, amp, strain))
    # THE FABRICATION TOLERANCE NOBODY HAS WRITTEN DOWN. The same flexibility says what a length
    # error costs: a member cut long by dL in a frame this stiff locks in dL/flex newtons before
    # the cell is ever evacuated, and there are 166 redundant loops to lock it into. The cutList
    # publishes 222.754 / 225.912 / 149.335 mm with no tolerance column, and the repo cites no
    # shop capability to hold them to, so this is a derived REQUIREMENT and not yet a gate: the
    # error budget that keeps the locked-in force under 10% of the design demand.
    budget = (0.10 * demand * float(flex.min()), 0.10 * demand * float(flex.max()))
    lines.append(
        f"length error is not free: {1.0 / flex.max():,.0f} to {1.0 / flex.min():,.0f} N per mm "
        f"of it. 0.10 mm of cut error locks in {0.10 / flex.max():,.0f} to "
        f"{0.10 / flex.min():,.0f} N, and {demand * flex.min():.3f} to "
        f"{demand * flex.max():.3f} mm locks in the whole {demand:.0f} N demand of the "
        f"{demand_family} — the smallest of the six family demands, and therefore the member "
        f"with the least room for a locked-in force. Holding "
        f"the locked-in force under 10% of demand needs every cut, and every printed base, "
        f"inside {budget[0]:.3f} to {budget[1]:.3f} mm — finer than one FDM layer, and finer "
        f"than the margins two of the passing proofs pass on. It is published as a tolerance "
        f"column on cutList and gated by nothing, because no shop capability is cited anywhere "
        f"in this repository to hold it to.")
    # WHAT IS NOT IN THE MATERIAL CARD, read off the card rather than asserted. Everything above
    # is isothermal, dry and instantaneous. A frame this stiff turns any strain into force, so
    # thermal expansion, moisture growth in a polyamide and duration-of-load on a permanently
    # evacuated joint are not second-order here — and none of them can be priced, because the
    # numbers do not exist in this repository. Naming the missing keys off MATERIALS itself
    # means this line goes away by itself the day someone sources them.
    card = set(vc.MATERIALS["PAHT_XY"])
    missing = [k for k in ("cte", "moistureGrowth", "creepKnockdown", "durationOfLoad")
               if k not in card]
    if missing:
        lines.append(
            f"and every number above is isothermal, dry and short-term: MATERIALS.PAHT_XY "
            f"carries {sorted(card)} and none of {missing}. At {1.0 / flex.max():,.0f} to "
            f"{1.0 / flex.min():,.0f} N per mm of length error, a strain that changes a "
            f"{2 * max(g['info'][u]['base'] for u, _ in nodes):.1f} mm printed load path by one "
            f"FDM layer is worth hundreds of newtons of self-stress in a frame with "
            f"{len(members) - len(nodes) + 1} redundant loops. No coefficient is invented here "
            f"to price it: the vacuum load is permanent and every capacity in this file is a "
            f"short-term ISO 527 tensile number, which is stated on every margin.")
    lines.append(
        "the bow alternative: " + "; ".join(
            f"{dl:.0f} mm of end shortening on a {L:.0f} mm member needs {amp:.2f} mm of bow "
            f"and {100 * s:.2f}% surface strain" for L, dl, amp, s in bows)
        + ", against roughly 1.5% ultimate. Even 3 mm breaks a tie.")
    return {"lines": lines,
            "data": {"flexMinMmPerN": float(flex.min()), "flexMaxMmPerN": float(flex.max()),
                     "forceFor20mmN": [round(prm["stub"] / flex.max()),
                                       round(prm["stub"] / flex.min())],
                     "membersOver0p1mmAt200N": int((hand * flex > 0.1).sum()),
                     "lengthToleranceAt10PctDemandMm": [round(budget[0], 4),
                                                        round(budget[1], 4)],
                     "newtonsPerMmOfLengthError": [round(1.0 / flex.max()),
                                                   round(1.0 / flex.min())],
                     "bow": [{"lengthMm": L, "shortenMm": dl, "amplitudeMm": round(a, 2),
                              "surfaceStrainPct": round(100 * s, 2)} for L, dl, a, s in bows]}}


def build_order_access(g, S, Q, RAD, prm, exhaustive):
    """A3 — is there an order in which every member has somewhere to come from?

    Testing extraction against the FINISHED article and concluding the build is impossible is
    the wrong question. Each member is offered only the geometry placed before its turn.
    """
    # 256 directions, not 128: at 128 one member of the inside-out order reports no escape and
    # at 256 it has one, so 128 was producing a false block. More directions can only FIND
    # escapes, never invent them, so the larger number is the honest default.
    members = g["members"]
    dirs = fib_dirs(512 if exhaustive else 256)
    lam = np.arange(0.0, 301.0, 3.0)

    def mid(k):
        a, b, _ = members[k]
        return float(np.linalg.norm((np.array(a, float) + np.array(b, float)) / 2.0))

    # THE ORDER IS INSIDE-OUT *AND TREE-CONSTRAINED* — the designer caught the seam
    # (2026-08-11): the spanning tree that sizes the stubs is rooted at a square-centre
    # joint, while a pure |midpoint| order walks out from the cell centre, so 27 of the 50
    # tree members used to come up AFTER some other member had already touched their
    # arriving joint. A tree member's two 20 mm stubs can only engage axially — that is
    # the entire reason closing members carry pilots — so a sequence in which its arriving
    # joint is already pinned by another member is not buildable, however clear the
    # straight-line access. The constraint is exactly the kinematic dependency: a joint's
    # DISCOVERY member (the tree member that arrives carrying it) must precede every other
    # member touching that joint. Kahn's construction with the same (|midpoint|, family,
    # u, v) key among the ready set keeps it deterministic and as inside-out as the
    # dependency allows, and the escape sweep below then proves access along the order
    # actually emitted, not the one retired.
    key_of = {k: (mid(k), members[k][2], members[k][0], members[k][1])
              for k in range(len(members))}
    tree_of = {arriving: k for k, _p, arriving in g["treeOrder"]}
    prereq = collections.defaultdict(set)
    for k, (a, b, _f) in enumerate(members):
        for u in (a, b):
            d = tree_of.get(u)
            if d is not None and d != k:
                prereq[k].add(d)
    dependents = collections.defaultdict(list)
    for k, ps in prereq.items():
        for p in ps:
            dependents[p].append(k)
    indeg = {k: len(prereq[k]) for k in range(len(members))}
    ready = [(key_of[k], k) for k in range(len(members)) if indeg[k] == 0]
    heapq.heapify(ready)
    order = []
    while ready:
        _, k = heapq.heappop(ready)
        order.append(k)
        for k2 in dependents[k]:
            indeg[k2] -= 1
            if indeg[k2] == 0:
                heapq.heappush(ready, (key_of[k2], k2))
    if len(order) != len(members):
        raise AssertionError("build order: the tree-dependency graph is cyclic, which a "
                             "BFS tree cannot be — the constraint wiring is wrong")
    blocked, placed, esc = [], [], {}
    for k in order:
        e = escape_scan(S, Q, RAD, k, np.array(placed), dirs, lam)
        if e is None:
            blocked.append(k)
        esc[k] = e
        placed.append(k)
    finished = sum(1 for k in range(len(members))
                   if escape_scan(S, Q, RAD, k, np.array([i for i in range(len(members))
                                                          if i != k]), dirs, lam) is None)
    rev = sorted(range(len(members)), key=lambda k: (-mid(k), members[k][2], members[k][0],
                                                     members[k][1]))
    blocked_rev, placed = 0, []
    for k in rev:
        if placed and escape_scan(S, Q, RAD, k, np.array(placed), dirs, lam) is None:
            blocked_rev += 1
        placed.append(k)
    lines = [
        f"against the FINISHED article {finished} of {len(members)} members have no "
        f"straight-line escape. Inside-out AND tree-constrained — ascending |midpoint| "
        f"among members whose end joints' discovery members are already placed, so every "
        f"joint arrives carried by its own tree member and every 20 mm stub engages "
        f"axially — blocks {len(blocked)} at their own turn. "
        f"Outside-in blocks {blocked_rev}. The order is therefore part of the contract and is "
        f"emitted as buildOrder; it is not left to the builder. Clearance is per pair, "
        f"r_i + r_j over the SKUs stock_build specifies ("
        + ", ".join(f"{r:.1f} mm x{n}" for r, n in
                    sorted(collections.Counter(np.round(RAD, 1)).items()))
        + "), and node bodies are covered by P9's envelope bound rather than modelled here."]
    return {"lines": lines,
            "data": {"rule": "inside-out, tree-constrained: ascending |midpoint| among "
                             "members whose end joints' discovery members are placed",
                     "memberIds": [f"{members[k][0]}-{members[k][1]}-{members[k][2]}"
                                   for k in order],
                     # The insertion line, reversed, for each member at its own turn — the
                     # page's assembly animation flies members in along these, so the
                     # approach on screen is the one this proof verified clear.
                     "escapeDirs": [None if esc[k] is None else
                                    [round(float(x), 4) for x in esc[k]] for k in order],
                     "blockedAtOwnTurn": len(blocked),
                     "blockedAgainstFinishedArticle": finished,
                     "blockedOutsideIn": blocked_rev,
                     "directions": len(dirs),
                     "clearanceRuleMm": "r_i + r_j from stock_build per member"}}


def free_end_sweep(g, prm, tree_order, S, Q, RAD):
    """A4 — the one motion in the build that is legal, measured precisely.

    Along the declared spanning tree each arriving node is retracted along its parent axis and
    its own arms are modelled as capsules; the parent member is excluded, because there zero
    clearance IS the engagement. Record the margin so a later change to stub, base or the graph
    is caught when it stops passing.
    """
    members = g["members"]
    r_arm = prm["pipe_id"] / 2.0 - prm["clearance"] + prm["rib_h"]   # spigot crest radius
    need = r_arm + float(RAD.max())         # arm capsule plus the widest pipe it can meet
    worst = (1e9, None, None)
    placed = []
    for k, parent, arriving in tree_order:      # BFS discovery order, not member index
        a, b = parent, arriving
        d = g["pos"][b] - g["pos"][a]
        d /= np.linalg.norm(d)
        for s in (prm["stub"], 15.0, 10.0, 5.0, 0.0):
            centre = g["pos"][b] + d * s
            arms = []
            for arm in g["incident"][b]:
                if arm["member"] == k:
                    continue
                arms.append((centre,
                             centre + arm["dir"] * (g["info"][b]["base"] + arm["stub"])))
            if not arms or not placed:
                continue
            P1 = np.array([x[0] for x in arms])[:, None, :]
            Q1 = np.array([x[1] for x in arms])[:, None, :]
            # Only the parent is excluded. In a spanning tree walked in discovery order it is
            # also the ONLY placed member incident on the arriving node — every other member at
            # b is a child and has not been placed yet — so this is the spec's rule and no
            # wider: everything the node could actually foul is still in the test.
            idx = np.array([i for i in placed if i != k])
            if len(idx) == 0:
                continue
            dd = (seg_seg_dist(P1, Q1, S[idx][None, :, :], Q[idx][None, :, :])
                  - RAD[idx][None, :]).min()
            gap = float(dd) - r_arm
            if gap < worst[0]:
                worst = (gap, k, s)
        placed.append(k)
    ok = worst[0] > 0
    return {"lines": [
        f"along the {len(tree_order)}-member spanning tree, walked in discovery order, the "
        f"tightest free-end retraction leaves {worst[0]:.3f} mm of clearance (member "
        f"{members[worst[1]][0]}-{members[worst[1]][1]} at {worst[2]:.0f} mm of retraction) "
        f"against a required {need:.2f} mm centre-line separation. This is the only legal "
        f"motion in the build: the tree "
        f"assembles freely and the whole problem is the {len(g['members']) - len(tree_order)} "
        f"members that close it. The margin is recorded so a later change to stub, base or the "
        f"graph is caught the moment it stops passing. Each placed member is at its own "
        f"specified radius, not at one global pipe_od."],
        "data": {"minClearanceMm": round(worst[0], 4), "feasible": bool(ok),
                 "armCapsuleRadiusMm": round(r_arm, 3),
                 "requiredCentreLineMm": round(need, 3),
                 "atMemberMm": worst[2]}}


def void_topology(g, prm):
    """A5 — does any bore close into a sealed cavity, and does a leak vent the whole lattice?"""
    reps, lines, data = class_representatives(g), [], {}
    for key, u in reps.items():
        inf = g["info"][u]
        gg = np.arange(-16.0, 16.001, 0.30)
        X, Y, Z = np.meshgrid(gg, gg, gg, indexing="ij")
        P = np.stack([X, Y, Z], -1).reshape(-1, 3).astype(np.float32)
        s = (field(P, inf, prm) < 0).reshape(X.shape)
        void = ~s
        sealed = void & ~border_reachable(void)
        origin = float(field(np.zeros((1, 3)), inf, prm)[0])
        ball = (X ** 2 + Y ** 2 + Z ** 2) <= prm["core_r"] ** 2
        data[str(key)] = {"enclosed": count_components(sealed) if sealed.any() else 0,
                          "enclosedCells": int(sealed.sum()),
                          "sdfAtOriginMm": round(origin, 4),
                          "solidFracOfCoreBall": round(float(s[ball].mean()), 4)}
    r_bore = prm["pipe_id"] / 2.0 - prm["clearance"] - prm["spigot_wall"]
    lines.append(
        "every node's bores share ONE cavity and it is vented: "
        + ", ".join(f"{k} {v['enclosed']} enclosed" for k, v in data.items())
        + f". Two {r_bore:.2f} mm bores at theta interconnect above r*cot(theta/2) = "
        + ", ".join(f"{r_bore / math.tan(math.radians(t / 2)):.3f} at {t:.0f} deg"
                    for t in (45, 60, 90))
        + f", so 45 and 60 degree pairs connect above the {prm['core_r'] * 0.3:.2f} mm bore "
          f"start and 90 degree pairs do not. A leak in any tube vents the whole lattice "
          f"interior, and glue can migrate between arms.")
    return {"lines": lines, "data": data}


def stl_versus_sdf(g, prm, manifest, rng):
    """A6 — the artefact against the design, with the resolution gap published.

    The SDF is authoritative for the DESIGN: its zero set is exact and only sampling is
    approximate. The STL is authoritative for the ARTEFACT. They answer different questions,
    and where the mesh cell is coarser than the feature, both numbers are printed.

    IT NOW EVALUATES THE FIELD, which its name always claimed. The volume clause compares each
    STL to a number written by the same gen_nodes run — an artefact against another artefact of
    the same run, which cannot tie the files on disk to the rule that made them. So every STL's
    vertices are also sampled against node_sdf: surface nets place a vertex inside the cell it
    found the crossing in, so |sdf| at a vertex is bounded by the mesh cell h, and a vertex that
    misses by more than that is a file that no longer matches the field. Vertices snapped onto
    a land plane are exempt by construction — gen_nodes moves them there after extraction.

    ITS SENSITIVITY IS ONE MESH CELL, and that is a real limit rather than a formality. Measured
    against the STLs on disk: core_r 8 -> 7 puts 518 vertices out, stub 20 -> 18 puts 9157 out,
    blend 4 -> 2 puts 1510 out, while core_r 8 -> 7.5 and spigot_wall 2.0 -> 1.8 stay inside
    0.884 mm and are invisible here. It also cannot see material ADDED away from the existing
    surface, because a mesh has no vertices where a new lump would be — that is what P15 is for.
    """
    lines, data = [], {}
    # The grid the STLs were actually cut on: gen_nodes.main() derives its half-extent from
    # the largest slot base the rule produces, and land_half_extent() is the transcription of
    # that expression this file already holds itself to. The old core_r + shoulder formula
    # here was 6.98 mm short of the real window, which made h — the one-cell sensitivity this
    # whole clause is stated in — 15% finer than any cell the mesh was built from.
    ext = land_half_extent(prm, g)
    res = (manifest or {}).get("res", 96)
    h = 2.0 * ext / (res - 1)
    need = int(math.ceil(2.0 * ext / prm["clearance"])) + 1
    lines.append(
        f"grid half-extent max(core_r+shoulder+stub+blend+6, pad_r+4, 22+stub) = {ext:.1f} mm, "
        f"so res {res} gives h = {h:.4f} mm — {h / prm['clearance']:.1f}x the "
        f"{prm['clearance']:.2f} mm clearance and {h / prm['rib_h']:.1f}x the "
        f"{prm['rib_h']:.2f} mm rib. Resolving the clearance needs res {need} "
        f"({need ** 3 / 1e6:.1f} M cells). With the current dense-grid extraction the STL will "
        f"never certify a fit, and this prover says so rather than picking a number.")
    if manifest:
        bad_vol, off_field, worst_dev, n_sampled = [], 0, 0.0, 0
        for ni, rec in enumerate(manifest["nodes"]):
            path = NODES_DIR / rec["file"]
            if not path.exists():
                bad_vol.append(f"{rec['file']}: listed but missing")
                continue
            v, t = read_binary_stl(path)
            vol = float(np.einsum("ij,ij->i", v[t[:, 0]],
                                  np.cross(v[t[:, 1]], v[t[:, 2]])).sum() / 6.0)
            if abs(round(vol) - rec["volumeMm3"]) > 1:
                bad_vol.append(f"{rec['file']}: mesh volume {vol:.0f} mm3, manifest "
                               f"{rec['volumeMm3']}")
            u = tuple(rec["u"])
            inf = g["info"][u]
            pick = rng.choice(len(v), size=min(len(v), 20000), replace=False)
            P = v[pick].astype(np.float32)
            on_land = np.zeros(len(P), bool)
            for n, off in zip(inf["landsPrint"], inf["offs"]):
                on_land |= np.abs(P @ n.astype(np.float32) - off) < h * 0.75
            dev = np.abs(field(P, inf, prm))[~on_land]
            n_sampled += int(dev.size)
            off_field += int((dev > h).sum())
            worst_dev = max(worst_dev, float(dev.max()) if dev.size else 0.0)
        data["volumeMismatches"] = len(bad_vol)
        data["stlVerticesOffTheField"] = off_field
        data["stlVerticesSampled"] = n_sampled
        data["worstVertexDeviationMm"] = round(worst_dev, 4)
        lines += bad_vol[:5]
        lines.append(f"{len(manifest['nodes']) - len(bad_vol)} of {len(manifest['nodes'])} STLs "
                     f"reproduce their manifest volume exactly by the divergence theorem over "
                     f"the mesh actually written.")
        lines.append(f"{n_sampled} vertices sampled off those meshes and evaluated in "
                     f"node_sdf: {off_field} sit further than one mesh cell ({h:.4f} mm) from "
                     f"the field's zero set, worst {worst_dev:.4f} mm. That is the clause that "
                     f"ties the 51 files on disk to the rule that made them; the volume clause "
                     f"above only ties them to another number from the same run. One mesh cell "
                     f"is also all it can resolve — it catches a field that has moved by about "
                     f"a millimetre and nothing finer, and it cannot see material added away "
                     f"from the surface, which is P15's job.")
    data.update({"gridHalfExtentMm": ext, "res": res, "cellMm": round(h, 4),
                 "resNeededForClearance": need})
    return {"lines": lines, "data": data}


def read_binary_stl(path):
    raw = path.read_bytes()
    n = _struct.unpack("<I", raw[80:84])[0]
    arr = np.frombuffer(raw, dtype=np.uint8, count=50 * n, offset=84).reshape(n, 50)
    tri = arr[:, 12:48].copy().view(np.float32).reshape(n, 3, 3).astype(np.float64)
    v = tri.reshape(-1, 3)
    t = np.arange(3 * n).reshape(n, 3)
    return v, t


def price_the_fix(ends, prm, closing, tau):
    """A7 — what the pilot cost, measured on the part that now exists rather than proposed.

    The bill has two halves and quoting the saving alone is not honest. The saving is mass and
    an article that can be assembled; the cost is pull-out at 332 member-ends, and it is a cost
    even though every member is in compression under the design load, because nothing in this
    repository says the article is never handled, lifted or evacuated unevenly.
    """
    closing_ends = [e for e in ends if e["isClosingMember"]]
    tree_ends = [e for e in ends if not e["isClosingMember"]]
    # The volume the pilot removed, measured: the section is uniform along the engaged length,
    # and the two stations (base + 0.25 s, base + 0.75 s) say so before the integral is taken.
    drift = max(abs(e["spigotAreaMm2"] - e["spigotAreaAtRootMm2"]) for e in ends)
    mean_sect = sum(e["spigotAreaMm2"] for e in closing_ends) / len(closing_ends)
    dv = mean_sect * (prm["stub"] - prm["pilot"])
    dm = dv * len(closing_ends) * prm["rho"] * 1e-9 * 1000.0
    bond_tree = sum(e["bondAreaMm2"] for e in tree_ends) / max(len(tree_ends), 1)
    bond_closing = sum(e["bondAreaMm2"] for e in closing_ends) / len(closing_ends)
    # What an external sleeve would have cost, which is the alternative this design did not
    # take: the cup does the same job in the node, at the collar's own wall.
    sleeve_len = 2.0 * prm["pilot"] + 8.0
    sleeve_v = math.pi * ((prm["pipe_od"] / 2.0 + prm["lip_wall"]) ** 2
                          - (prm["pipe_od"] / 2.0 + prm["clearance"]) ** 2) * sleeve_len
    sleeve_m = sleeve_v * len(closing) * prm["rho"] * 1e-9 * 1000.0
    return {"lines": [
        f"{len(closing_ends)} closing member-ends are engaged {prm['pilot']:.0f} mm instead of "
        f"{prm['stub']:.0f}, which removes {dm:.0f} g of printed spigot (measured section "
        f"{mean_sect:.2f} mm2, uniform to {drift:.3f} mm2 between the two stations) and is "
        f"what makes the article assemblable at all. It costs pull-out: mean bonded area falls "
        f"from {bond_tree:.1f} mm2 at a tree end to {bond_closing:.1f} at a closing one, so at "
        f"the same {tau:.0f} MPa line a closing end holds {bond_closing * tau:.0f} N against "
        f"{bond_tree * tau:.0f}. The cup is what keeps that from being "
        f"{math.pi * prm['pipe_id'] * prm['pilot'] * tau:.0f} N — the spigot alone — and it "
        f"costs nothing to carry, where the external sleeves that would restore the same "
        f"capture weigh {sleeve_m:.0f} g over {len(closing)} members."],
        "data": {"endsShortened": len(closing_ends),
                 "pullOutTreeEndN": round(bond_tree * tau),
                 "pullOutClosingEndN": round(bond_closing * tau),
                 "pullOutClosingSpigotOnlyN": round(math.pi * prm["pipe_id"]
                                                    * prm["pilot"] * tau),
                 "nodeMassSavedG": round(dm, 1), "sleeveMassAvoidedG": round(sleeve_m, 1),
                 "sectionUniformityMm2": round(drift, 4)}}


def land_half_extent(prm, g):
    """The window a land silhouette must be measured in: the same expression gen_nodes.main()
    uses for the extraction grid, because that is the box the part is known to fit in.

    It was 16.0 mm, hard-coded, while an in-plane arm runs to base + stub = 33.96 mm. Every
    published silhouette touched the window edge, and since `holes` is defined as the void the
    BORDER cannot reach, a groove that ran off the edge was classified open rather than
    enclosed. enclosedHolesMm2 = 0.00 happens to survive the correction, but it was not
    established by the cropped measurement, and the solid areas roughly doubled.

    IT TOOK THE MAX OVER core_r + shoulder AND RETURNED 42.0 WHILE THE PART REACHED 42.98. That
    expression was gen_nodes' old one; gen_nodes.main() now derives the window from the largest
    base its own slot rule produces, because the per-arm rim SKU pushed the worst base from
    16.38 mm to 18.98 and a fixed window clipped the mesh. This function's docstring claimed to
    be "the same expression gen_nodes.main() uses" while being 6.98 mm short of it — a probe
    that stops 0.98 mm inside the tallest arm's own material and says the region past it is
    empty. `g` is required, not a default: the window is a property of the graph the part was
    grown from, and a caller holding only `prm` cannot know it.
    """
    max_base = max(inf["base"] for inf in g["info"].values())
    return max(max_base + prm["stub"] + prm["blend"] + 6.0,
               prm["pad_r"] + 4.0, 22.0 + prm["stub"])


def land_integrity(g, prm, exhaustive):
    """Every land: nothing proud of the plane, and what the mating face actually looks like.

    (b) is a tautology of the SDF as written — the lands are applied last as d = max(d, P.n), so
    d >= P.n > 0 outside the plane and no solid can stand proud. The test is here so that a
    change which moves the truncation earlier, where a blend could round it back off, is caught
    the day it is made rather than on a bed.
    """
    proud, flaws, report = [], [], {}
    half = land_half_extent(prm, g)
    # Grids are quoted as a CELL SIZE and the count follows the window, so widening the window
    # from 16 mm to the part's own 42 mm does not silently coarsen anything. The proud test runs
    # at 0.40 mm because it is a boolean over a whole plane — material rounded back over a land
    # is a broad region, never one cell — and covering 2.6x more plane matters more there than
    # a finer cell over a sixth of it.
    n_proud = int(2.0 * half / 0.40) + 1
    n_pub = int(2.0 * half / 0.082) + 1
    n_cmp = int(2.0 * half / 0.083) + 1
    # THE CLASS KEY IS A CONGRUENCE FINGERPRINT NOW, not a name. A land silhouette is the solid
    # cut by the mating plane, so it depends on where every arm sits relative to that plane AND
    # on how long each arm is — and engagement stopped being uniform the day the closing ends
    # got a pilot. (role, arms, landIndex) used to be enough because every arm was 20 mm; the
    # first thing that happened when it stopped being enough was two lattice nodes of the same
    # "class" silhouetting 782 and 627 mm2, and two hexagon lands on ONE rim vertex differing
    # by 2 mm2 because the node's single tree arm stands to one side of the mirror plane.
    #
    # The fingerprint is built from dot products only, so it is invariant under every isometry
    # that fixes the land plane — rotations and reflections alike, and a mirrored silhouette
    # has the same area. Each arm contributes its cosine to the land normal, its engagement,
    # and the sorted list of (cosine, engagement) to every other arm; two lands with the same
    # multiset of those are congruent. The SUNKEN FRAME is part of the shape now, so the
    # plane's own offset, the sink magnitude and the post axis's cosine to this land join the
    # key: two lands whose arms match but whose nodes sank differently silhouette differently,
    # and a class key blind to that would flag real geometry as a broken measurement.
    def land_fingerprint(inf, li):
        nrm = inf["lands"][li]
        dirs, stubs = inf["dirs"], inf["stubs"]
        out = []
        for i, d in enumerate(dirs):
            nb = tuple(sorted((round(float(d @ dirs[j]), 6), stubs[j])
                              for j in range(len(dirs)) if j != i))
            out.append((round(float(d @ nrm), 6), stubs[i], nb))
        frame = (round(inf["offs"][li], 6),
                 round(float(np.linalg.norm(inf["sinkVec"])), 6),
                 round(float(inf["postAxis"] @ nrm), 6)
                 if inf["postAxis"] is not None else None)
        return (frame, tuple(sorted(out)))

    classes = collections.defaultdict(list)
    for ni, (u, role) in enumerate(g["nodes"]):
        inf = g["info"][u]
        for li, nrm in enumerate(inf["lands"]):
            maps, X, Y, cell = land_maps(u, li, g, prm, half, n_proud, [-0.02])
            if maps[0].any():
                proud.append(f"node_{ni} land{li}")
            classes[(role, len(inf["dirs"]), land_fingerprint(inf, li))].append((ni, u, li))
    # The published silhouette is always measured on one representative per class at the full
    # 1025 grid, so the number is the same in both modes. What changes is how many nodes are
    # checked to AGREE with it: one more per class in fast mode, all of them under
    # --exhaustive, both on a coarser grid because agreement is a comparison and not a
    # publication.
    # Classes are numbered in a stable order — by role, arm count, then their first node and
    # land — because a fingerprint is not a name a reader can use.
    order = sorted(classes, key=lambda k: (k[0], k[1], classes[k][0][0], classes[k][0][2]))
    todo = [(f"{k[0]}/{k[1]}arm/class{ci}", classes[k][0][0], classes[k][0][1],
             classes[k][0][2], len(classes[k])) for ci, k in enumerate(order)]

    def coarse_area(u, li):
        """Area, and the discretisation bound that goes with it.

        TWO CONGRUENT SHAPES ON TWO GRIDS DO NOT MEASURE THE SAME. The comparison used to run
        between nodes of one role, which are images of each other under a symmetry that also
        maps the sampling grid onto itself, so a 0.5 mm2 tolerance held. A class can now
        contain two lands of the SAME node — the two hexagon faces of a rim vertex are mirror
        images — and their grids are not related by that mirror. Every cell the boundary passes
        through can fall either way, so the bound is the boundary's own cell count times the
        cell: about 8 mm2 on a 195 mm2 land at this grid, and 20x smaller than the 155 mm2
        difference that exposed the class key in the first place.
        """
        (s,), _, _, c = land_maps(u, li, g, prm, half, n_cmp, [0.02])
        edge = s & ~(np.roll(s, 1, 0) & np.roll(s, -1, 0)
                     & np.roll(s, 1, 1) & np.roll(s, -1, 1))
        return float(s.sum()) * float(c), float(edge.sum()) * float(c)

    for ci, k in enumerate(order):
        members_ = classes[k]
        if len(members_) < 2:
            continue
        ref, tol = coarse_area(members_[0][1], members_[0][2])
        for ni, u, li in (members_[1:] if exhaustive else members_[1:2]):
            got, tol2 = coarse_area(u, li)
            if abs(ref - got) > max(tol, tol2):
                flaws.append(
                    f"land class {k[0]}/{k[1]}arm/class{ci} is not uniform: node_"
                    f"{members_[0][0]} land{members_[0][2]} silhouettes {ref:.2f} mm2 and "
                    f"node_{ni} land{li} {got:.2f}, past the {max(tol, tol2):.2f} mm2 the "
                    f"grid can account for — so one representative cannot speak for the class")
    for label, ni, u, li, n_in_class in todo:
        (solid,), X, Y, cell = land_maps(u, li, g, prm, half, n_pub, [0.02])
        # THE PRECONDITION FOR EVERY NUMBER BELOW. `holes` is the void the array border cannot
        # reach, so a silhouette that runs off the window turns an enclosed hole into an open
        # groove by definition. Publishing an area from a window the part touches is publishing
        # a crop, so the touch is a hard failure rather than a footnote.
        if (solid[0, :].any() or solid[-1, :].any()
                or solid[:, 0].any() or solid[:, -1].any()):
            flaws.append(
                f"land silhouette {label} (node_{ni}) touches the {half:.1f} mm measurement "
                f"window — every area and component count on this land is a crop, and "
                f"enclosedHolesMm2 is not established because the crop edge is being read as "
                f"the outside world")
        holes = (~solid) & (~border_reachable(~solid))
        hull = convex_hull_mask(solid, X, Y)
        groove = hull & (~solid) & (~holes)
        report[label] = {
            "solidMm2": round(float(solid.sum()) * float(cell), 2),
            "hullMm2": round(float(hull.sum()) * float(cell), 2),
            "enclosedHolesMm2": round(float(holes.sum()) * float(cell), 3),
            "grooveMm2": round(float(groove.sum()) * float(cell), 2),
            "grooveComponents": count_components(groove),
            "windowHalfMm": round(half, 2), "cellMm": round(float(cell) ** 0.5, 4),
            "representative": f"node_{ni} land{li}", "landsInClass": n_in_class}
    return report, proud, flaws


def insertion_sweep(g, prm, closing, exhaustive):
    """P8's bound, asked of the field instead of the algebra.

    For one closing member per end class (all 216 with --exhaustive) the pipe is offered to its
    far socket at a range of tilts and insertion depths, and node_sdf is asked whether the
    pipe's own material is inside the node's.

    THE PIVOT IS THE MIDDLE OF THE ENGAGED LENGTH, not the end face. A peg in a hole rocks
    about its middle and touches the bore at both ends, which is what makes the limit
    phi <= D/e; pivoting about the end face is a different and tighter motion, and modelling it
    reports a jam at 0.36 degrees that the builder does not have. Fast mode runs the
    representatives and leans on the closed form for the rest, which is stated in --help and in
    the summary line.

    THE PIPE IS AN ANNULUS, not a line of radius pipe_id/2. The fit that decides a peg-in-hole
    limit has two surfaces — the bore over the spigot AND the outside diameter inside the slot's
    outer wall at pipe_od/2 + clearance — and sampling only the first leaves half the fit
    untested. Resolution is set by measurement, not by taste: SWEEP_AZ/SWEEP_AX were refined
    until the engagement reported at the peg-in-hole limit stopped moving (see the note beside
    them), and both are finer than the 0.15 mm clearance being adjudicated.

    AND IT IS THE MEMBER'S OWN ANNULUS, rebuilt per representative from arm_pipe(). The radii
    used to be hoisted out of the loop at the global 4.00-5.00 mm, which was harmless only
    while every socket was drawn 10x8. The moment the rim got the 14x12 tube its analysis buys,
    its spigot crest moved out to rim_pipe_id/2 - clearance = 5.85 mm and the probe's own band
    ran 0.85 mm INSIDE the arm's own solid spigot — reporting all 72 rim ends jammed at
    phi = 0.000, the fully seated pose, where there is no tilt to blame and no pilot depth,
    chamfer or entry angle could have helped. A real 14x12 tube has a 6.00 mm bore and is
    nowhere near r = 5.00. The lesson is the one P4 and P9 already learned: a probe carrying a
    global SKU measures a member nobody is cutting.
    """
    reps, seen = [], set()
    for k in closing:
        a, b, fam = g["members"][k]
        for u in (a, b):
            key = (g["role"][u], len(g["info"][u]["dirs"]), len(g["info"][u]["lands"]), fam)
            if key in seen and not exhaustive:
                continue
            seen.add(key)
            reps.append((k, u))
    az = (np.arange(SWEEP_AZ) + 0.5) * (2 * np.pi / SWEEP_AZ)
    rows, worst = [], (1e9, None)
    for k, u in reps:
        inf = g["info"][u]
        ai = next(i for i, arm in enumerate(g["incident"][u]) if arm["member"] == k)
        axis = inf["armsPrint"][ai]
        w, _ = arm_frame(axis)                     # the tilt axis, perpendicular to the arm
        base, stub = inf["base"], inf["stubs"][ai]
        a, b, _fam = g["members"][k]
        P_cut = (member_length(g, a, b) - g["info"][a]["base"] - g["info"][b]["base"])
        # THE TUBE THIS MEMBER IS ACTUALLY CUT FROM. Inside the loop, from the same arm_pipe()
        # the generator draws the socket with — see the docstring for what a global band did to
        # the 72 rim ends.
        od, idm = arm_pipe(_fam, prm)
        radii = np.linspace(idm / 2.0, od / 2.0, SWEEP_NR)
        # THE WHOLE PATH, not two poses. A closing member is dropped in at the tilt that clears
        # both pilots and then rotated down while it slides home, and the kinematic identity
        # e_A + e_B = s_A + s_B - P(1 - cos phi) says exactly how much engagement each tilt
        # allows: e(phi) = s - P(1 - cos phi)/2 on a member whose two pilots are equal. So the
        # sweep asks the field for the pose the BUILDER is in at each tilt, from the entry
        # angle down to zero, and the member is assemblable only if every one of them is clear.
        # THE MEMBER IS CUT SHORT, and without that none of this works. A square-cut tube
        # tilted by phi puts its end-face corner Ro sin(phi) below the plane its centre sits
        # in, while the tilt only buys P(1 - cos phi)/2 of retreat — so under about 4 Ro / P
        # (5.3 deg on the long cut) the corner is inside the seat at EVERY axial position, and
        # a member whose length equals the seat gap cannot be rotated down into the last few
        # degrees at all. gen_nodes.swing_relief derives how much shorter each end has to be
        # cut and publishes it on every cutList row; the pose below uses it, so this sweep is
        # what makes that requirement a requirement rather than a remark.
        relief = swing_relief(P_cut, prm, _fam)
        s_eff = stub - relief
        phi_need = math.degrees(math.acos(max(-1.0, 1.0 - 2.0 * s_eff / P_cut)))
        # The second extra pose is 4 Ro / P, the angle at which the end-face corner finally
        # climbs back above the seat plane, so it is the top of the band swing_relief exists to
        # clear and it has to be sampled at THIS member's Ro. At the global one a rim member was
        # sampled at 5.37 deg when its own band runs to 7.50 — 2.13 deg of the only region this
        # pose exists to look at, unvisited.
        phis = np.unique(np.concatenate([
            np.linspace(0.0, phi_need, 11),
            [math.degrees(math.atan(2.0 * prm["clearance"] / max(s_eff, 1e-9))),
             math.degrees(math.atan(2.0 * od / P_cut))]]))
        # Start 0.02 mm off the end face. At t = base exactly the seating slot is NOT cut —
        # gen_nodes writes max(base - t, ...), which is zero and therefore not negative there —
        # so a ring sampled on that plane reads solid and every representative would report a
        # jam it does not have. The offset is a tenth of the fit clearance.
        s_ax = np.linspace(0.02, stub + 4.0, SWEEP_AX)
        pts, tag = [], []
        for phi in phis:
            c, s = math.cos(math.radians(phi)), math.sin(math.radians(phi))
            ap = c * axis + s * np.cross(w, axis)
            e1, e2 = arm_frame(ap)
            circ = (np.cos(az)[:, None] * e1 + np.sin(az)[:, None] * e2)
            ring = (radii[:, None, None] * circ[None, :, :]).reshape(-1, 3)
            e = max(0.0, s_eff - P_cut * (1.0 - c) / 2.0)     # the pose the identity allows
            mid = (base + stub - e / 2.0) * axis              # middle of the engaged length
            P = (mid + (s_ax - e / 2.0)[:, None, None] * ap
                 + ring[None, :, :]).reshape(-1, 3)
            pts.append(P)
            tag.append((phi, e, len(P)))
        allP = np.vstack(pts).astype(np.float32)
        sd = field(allP, inf, prm, ribs=0)      # the ribs crush; see field()'s docstring
        cur, blocked = 0, []
        for phi, e, n in tag:
            m = float(sd[cur:cur + n].min())
            cur += n
            if m < 0.0:
                blocked.append((round(phi, 3), round(e, 3)))
            if m < worst[0]:
                worst = (m, f"{g['members'][k][0]}-{g['members'][k][1]} at {phi:.2f} deg")
        rows.append((k, u, stub, phi_need, blocked, relief, (od, idm)))
    clear = [r for r in rows if not r[4]]
    blocked_reps = [f"{g['members'][r[0]][0]}-{g['members'][r[0]][1]} at {r[4][0][0]} deg"
                    for r in rows if r[4]]
    # The SKUs are COUNTED off the members that were swept, not written down. A sentence that
    # names one tube while the loop probes two is how the rim ends came to be measured against
    # a pipe nobody buys, and a hand-typed pair would go stale the day a third SKU appears.
    sku_txt = ", ".join(f"{od:.0f}x{idm:.0f} on {n}" for (od, idm), n in
                        sorted(collections.Counter(r[6] for r in rows).items(),
                               key=lambda kv: (-kv[1], kv[0])))
    return (len(rows) - len(clear), blocked_reps,
            [f"field sweep over {len(rows)} closing-member representatives, each member "
             f"modelled as ITS OWN annulus ({sku_txt}) at "
             f"{SWEEP_NR}x{SWEEP_AX}x{SWEEP_AZ} points and pivoted about the middle of the "
             f"engaged length: {len(clear)} of {len(rows)} are clear at EVERY pose on the "
             f"swing-in path, from the entry tilt "
             f"{min(r[3] for r in rows):.2f}-{max(r[3] for r in rows):.2f} deg down to seated, "
             f"with the engagement at each tilt taken from the kinematic identity rather than "
             f"searched for. Tightest approach anywhere on any path {worst[0]:.3f} mm "
             f"({worst[1]}). Pilots are {min(r[2] for r in rows):.1f}-"
             f"{max(r[2] for r in rows):.1f} mm, each member cut {min(r[5] for r in rows):.2f}-{max(r[5] for r in rows):.2f} mm short at each end "
             f"so its own end corner clears the seat; the {prm['ribs']} crush ribs are excluded "
             f"because they deform, and only the far node is modelled — P9's envelope bound "
             f"is what covers the rest of the article."],
            len(rows))


def class_representatives(g):
    reps = {}
    for u, r in g["nodes"]:
        key = (r, len(g["info"][u]["dirs"]), len(g["info"][u]["lands"]))
        reps.setdefault(key, u)
    return reps


