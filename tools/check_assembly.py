def arm_frame(d):
    """Two unit vectors spanning the plane normal to an arm.

    Same reference choice node_sdf's rib branch makes, so probe azimuths are indexed the same
    way the ribs are phased. It matters for reading a rib band; it does not matter for any
    full-circle integral, which is every area in this file.
    """
    ref = np.array([0.0, 0.0, 1.0]) if abs(d[2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    e1 = np.cross(d, ref)
    e1 /= np.linalg.norm(e1)
    return e1, np.cross(d, e1)


def build_graph(prm):
    """The article, its incidence, and every quantity that costs no field evaluation.

    ENGAGEMENT IS PER MEMBER-END, and that is the whole of the closing-member fix, so it is
    carried here rather than read off `prm`: gen_nodes.spanning_tree decides which 50 members
    have a free end, those 100 ends get the full stub, and the other 332 get the pilot. Every
    probe below asks the arm for its own engagement. A file that reads prm["stub"] measures a
    part that is not on the disk at 332 of 432 ends.
    """
    nodes, members, tally = article_graph()
    index = {u: i for i, (u, _) in enumerate(nodes)}
    role = {u: r for u, r in nodes}
    tree, tree_order = spanning_tree(nodes, members)

    # THE SUNKEN FRAME, in the same two passes gen_nodes.main() takes. Sink decisions are
    # judged on the NOMINAL lattice directions — boundary_frame's contract — and then every
    # position, direction, angle and cut below is re-derived from the sunken article. A model
    # that kept the nominal directions here would measure sockets a fraction of a degree off
    # the arms the STLs were grown around, and hold the mating lands to planes through centres
    # the joints no longer occupy.
    nominal = {u: [] for u, _ in nodes}
    for k, (a, b, fam) in enumerate(members):
        d = np.array(b, float) - np.array(a, float)
        d /= np.linalg.norm(d)
        nominal[a].append((d, fam))
        nominal[b].append((-d, fam))
    frame_of = {u: boundary_frame(u, [d for d, _ in nominal[u]],
                                  [f for _, f in nominal[u]], prm) for u, _ in nodes}
    pos = {u: np.array(u, float) * HALF + frame_of[u][0] for u, _ in nodes}

    # Arm order is the order gen_nodes.main() builds incident[] in, so endId is stable and
    # freezable: iterate members in graph order, append d at a and -d at b. tiltMaxDeg is the
    # largest angle the sink turned any member off its lattice direction — the article's own
    # bound on how far a real elevation may sit from a lattice one, which P13 holds every end
    # to instead of a typed list the sink made exactly wrong.
    incident = {u: [] for u, _ in nodes}
    tilt_max = 0.0
    for k, (a, b, fam) in enumerate(members):
        nd = np.array(b, float) - np.array(a, float)
        nd /= np.linalg.norm(nd)
        d = pos[b] - pos[a]
        d /= np.linalg.norm(d)
        tilt_max = max(tilt_max, math.degrees(
            math.acos(max(-1.0, min(1.0, float(nd @ d))))))
        stub = prm["stub"] if k in tree else prm["pilot"]
        incident[a].append({"dir": d, "family": fam, "other": b, "member": k, "stub": stub,
                            "closing": k not in tree})
        incident[b].append({"dir": -d, "family": fam, "other": a, "member": k, "stub": stub,
                            "closing": k not in tree})

    info = {}
    for u, r in nodes:
        dirs = [a["dir"] for a in incident[u]]
        # PER-ARM SKU, the same quantity gen_nodes builds the part from. Without it this
        # model measured every socket at the main 10 mm tube while the generator cut the rim
        # at 14 — the prover would then be proving a part nobody prints.
        kinds = [a["family"] for a in incident[u]]
        base, min_ang, need = slot_base(dirs, prm, kinds)
        sink_vec, land_pairs = frame_of[u]
        lands = [n for n, _ in land_pairs]
        offs = [o for _, o in land_pairs]
        sink = float(np.linalg.norm(sink_vec))
        post_axis = (-sink_vec / sink) if sink > 1e-9 else None
        # THE PRINT FRAME IS MEASURED FOR EVERY NODE NOW, exactly as gen_nodes does it: a
        # sunken node's only flat at a mating plane is its post top, nothing to seat a print
        # on, so the bed-normal search that used to serve the 13 landless joints serves all
        # 51. It needs the same per-arm engagement and bore starts the generator builds the
        # part from. Passing anything less would have this model proving a part in one
        # orientation while gen_nodes emitted it in another, and every elevation, every
        # allowable interpolated on elevation and every overhang in the report would be about
        # a part nobody prints.
        stubs = [a["stub"] for a in incident[u]]
        bores = [bore_start(d, lands, prm, kd, offs) for d, kd in zip(dirs, kinds)]
        R = print_frame([], dirs, prm, base, stubs, bores, kinds)
        info[u] = {"dirs": dirs, "lands": lands, "base": base, "minAng": min_ang,
                   "need": need, "R": R, "role": r, "kinds": kinds,
                   "stubs": stubs, "bores": bores,
                   # The frame the node sits in: each land plane's height above the sunken
                   # centre (P.n <= off is the part's side), and the post that climbs back.
                   "offs": offs, "sinkVec": sink_vec, "postAxis": post_axis,
                   "postPrint": (R @ post_axis) if post_axis is not None else None,
                   "armsPrint": [R @ d for d in dirs],
                   "landsPrint": [R @ n for n in lands]}
    return {"nodes": nodes, "members": members, "tally": tally, "index": index,
            "role": role, "incident": incident, "info": info, "tree": tree,
            "treeOrder": tree_order, "pos": pos, "tiltMaxDeg": tilt_max}


def field(P, inf, prm, ribs=None):
    """node_sdf for one node, with that node's own per-arm engagement and bore starts.

    One call site for the field means one place where a new per-arm quantity has to be wired,
    and no probe can quietly measure a part built from the defaults.

    `ribs` overrides the rib count. THE CRUSH RIB IS THE ONE COMPLIANT FEATURE IN THE JOINT:
    it stands rib_h - clearance inside the pipe's bore on purpose and deforms on assembly, so
    a rigid-body question — can this pipe reach its seat, is this volume empty — has to be
    asked of the field that does not draw it, or it answers "no" 432 times about the feature
    that is correct. P7 is what proves the ribs are there; nothing else may lean on them.
    """
    p = prm if ribs is None or ribs == prm["ribs"] else dict(prm, ribs=ribs)
    return node_sdf(np.asarray(P, np.float32),
                    [a.astype(np.float32) for a in inf["armsPrint"]],
                    [n.astype(np.float32) for n in inf["landsPrint"]], p,
                    inf["role"] == "hexHub", inf["base"], inf["stubs"], inf["bores"],
                    inf["kinds"], land_offs=inf["offs"], post_axis=inf["postPrint"])


def member_length(g, a, b):
    # Between SUNKEN centres, not lattice points: the sink shortens every boundary-adjacent
    # member, and the cut the builder makes is this length less both bases. The nominal
    # lattice pitch survives only in the article's span — the land posts keep the faces there.
    return float(np.linalg.norm(g["pos"][b] - g["pos"][a]))


# ------------------------------------------------------------------ topology and rigidity --
def topology(g):
    nodes, members = g["nodes"], g["members"]
    V, E = len(nodes), len(members)
    # The tree is gen_nodes' own — the generator decides which ends carry the full stub, and a
    # second BFS here could disagree with it without either file changing. Connectivity is
    # re-established independently anyway, because C is what the cycle rank is computed from.
    tree, tree_order = g["tree"], g["treeOrder"]
    adj = collections.defaultdict(list)
    for k, (a, b, _) in enumerate(members):
        adj[a].append((b, k))
        adj[b].append((a, k))
    seen, queue = {nodes[0][0]}, collections.deque([nodes[0][0]])
    while queue:
        u = queue.popleft()
        for v, _k in adj[u]:
            if v not in seen:
                seen.add(v)
                queue.append(v)
    components = 1 if len(seen) == V else 1 + len([u for u, _ in nodes if u not in seen])

    # Rigidity matrix: one row per member, +/- its unit direction at its two endpoints. Its
    # rank is 3V-6 for a rigid framework, and E - rank is the static indeterminacy. That is
    # NOT the assembly number and A1 says so. Directions are the SUNKEN article's — the frame
    # that is built is the frame whose rigidity is claimed.
    R = np.zeros((E, 3 * V))
    for k, (a, b, _) in enumerate(members):
        d = g["pos"][b] - g["pos"][a]
        d /= np.linalg.norm(d)
        ia, ib = g["index"][a], g["index"][b]
        R[k, 3 * ia:3 * ia + 3] = d
        R[k, 3 * ib:3 * ib + 3] = -d
    rank = int(np.linalg.matrix_rank(R))

    degrees = collections.Counter()
    for a, b, _ in members:
        degrees[a] += 1
        degrees[b] += 1
    return {"V": V, "E": E, "C": components, "cycleRank": E - V + components,
            "spanningTree": sorted(tree), "treeOrder": tree_order, "rigidityRank": rank,
            "staticIndeterminacy": E - rank,
            "degreeHistogram": dict(sorted(collections.Counter(degrees.values()).items())),
            "degrees": degrees}


# ------------------------------------------------------------------- lands: exact geometry --
def _cutting_lands(d, lands, offs, r, t_lo, t_hi):
    """The subset of this node's lands that reach a radius-r feature on arm d over [t_lo, t_hi].

    A land is the half-space P.n <= off — an OFFSET plane since the frame sank, `off` being the
    nominal face's height above the sunken centre. A point of the feature circle at axial s and
    azimuth psi sits at height s*(d.n) + r*sin(beta)*sin(psi + psi0), beta the arm-plane angle,
    so the feature's highest excursion over the interval is max(t_lo*(d.n), t_hi*(d.n)) +
    r*sin(beta), and a land below that never touches it. Exact, no sampling.
    """
    out = []
    for n, off in zip(lands, offs):
        c = float(d @ n)
        sinb = math.sqrt(max(0.0, 1.0 - c * c))
        if max(t_lo * c, t_hi * c) + r * sinb > off + 1e-9:
            out.append((n, off))
    return out


def _ring_fracs(d, cutting, r, ts, na):
    """Surviving azimuth fraction of the radius-r circle at each station in ts — the same
    quantity a solid-fraction probe of that ring measures, computed from the plane algebra."""
    e1, e2 = arm_frame(d)
    phi = (np.arange(na) + 0.5) * (2.0 * np.pi / na)
    ok = np.ones((len(ts), na), dtype=bool)
    for n, off in cutting:
        c = float(d @ n)
        rad = np.cos(phi) * float(e1 @ n) + np.sin(phi) * float(e2 @ n)
        ok &= (np.asarray(ts, float)[:, None] * c + r * rad[None, :]) <= off + 1e-12
    return ok.mean(axis=1)


def land_cuts(d, lands, offs, r, t_lo, t_hi):
    """Which of this node's lands cut a radius-r feature on this arm, and the worst surviving
    fraction of its circumference anywhere in the feature's own axial run.

    Before the frame sank this was the whole of P5: every land was a plane through the node's
    centre, an arm lying IN one kept exactly the dihedral's fraction of its socket — 0.500,
    0.348, 0.304 — and no radius or station changed the answer. The lands are offset planes
    now, boundary_frame() reserves collar radius plus land_margin under every one of them, and
    the correct census is zero cut features. This function is what notices when that stops
    being true: shrink the sink, thicken a collar, tilt an arm, and the fraction it returns is
    exact for the geometry as built — closed form deciding WHETHER a land reaches the feature,
    a fine azimuth grid intersecting the survivors when one does. The station resolution is
    257 across the run and the azimuth grid 5760, a tenth of a degree, only ever paid on a
    feature that is actually cut.
    """
    cutting = _cutting_lands(d, lands, offs, r, t_lo, t_hi)
    if not cutting:
        return [], 1.0
    ts = np.linspace(t_lo, t_hi, 257)
    return [n for n, _ in cutting], float(_ring_fracs(d, cutting, r, ts, 5760).min())


def ring_wrap_exact(d, lands, offs, r, ts, na):
    """What the wrap-ring probe MUST read if the field and this algebra describe the same
    socket: the mean surviving fraction over exactly the probe's own stations, radius and
    azimuth count. Mirrors the measurement so the corroboration compares like with like."""
    cutting = _cutting_lands(d, lands, offs, r, float(min(ts)), float(max(ts)))
    if not cutting:
        return 1.0
    return float(_ring_fracs(d, cutting, r, ts, na).mean())


# ------------------------------------------------------- the pair-region envelope (no SDF) --
# Feature boxes, every dimension read off gen_nodes' own expressions rather than typed. A
# feature is (r_lo, r_hi, t_lo, t_hi) about its own arm; t_hi = None means "as far as it goes",
# which is always further than any overlap this chart can see.
def feature_boxes(prm):
    """The V3 joint has four features about an arm, not five, and one of them moved.

    The outer lip used to be a cup around the node's own core, (0, core_r+lip) along the arm at
    radius up to pipe_od/2 + lip_wall, and it ended 3.5 mm short of every seat in the article.
    It is now the top of the COLLAR — the same outer radius, but spanning base - shoulder to
    base + cup, so it is around the pipe rather than around the core. The slot's inner radius is
    the ribbed spigot's own profile, so the widest void it can cut is still the bare spigot
    radius and that is what the box carries.
    """
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]              # 3.85
    crest = spig_r + (prm["rib_h"] if prm["ribs"] else 0.0)       # 4.10
    ro_slot = prm["pipe_od"] / 2.0 + prm["clearance"]             # 5.15
    r_collar = prm["pipe_od"] / 2.0 + prm["lip_wall"]             # 6.60
    r_bore = spig_r - prm["spigot_wall"]                          # 1.85
    t_bore0 = prm["core_r"] * 0.3                                 # 2.40, the smallest of them
    reach = None
    return {
        "slot": (spig_r, ro_slot, "BASE", reach),
        "bore": (0.0, r_bore, t_bore0, reach),
        "spigot": (0.0, crest, 0.0, reach),
        "collar": (0.0, r_collar, "BASE", reach),
        "pipe": (0.0, prm["pipe_od"] / 2.0, "BASE", reach),
        "core": None,        # a sphere, handled in closed form: |P| <= core_r
    }


# (name, featureA, featureB, symmetric, comparand, bias). "symmetric" means the threshold is
# max min(tA, tB) rather than max tA. "comparand" names what the threshold is held against:
# BASE for anything a bigger slot start cures, T_BORE0 for the two bore pairs, which it does not
# — raising base only lengthens the bore. "bias" is what has to be ADDED to make the number
# comparable to base: the collar starts a shoulder earlier than the slot does, so a collar pair
# that clears at T needs base >= T + shoulder.
PAIR_TYPES = [
    ("slot x slot", "slot", "slot", True, "BASE", 0.0),
    ("slot x spigot", "slot", "spigot", False, "BASE", 0.0),
    ("slot x collar", "slot", "collar", True, "BASE", "SHOULDER"),
    ("pipe x pipe", "pipe", "pipe", True, "BASE", 0.0),
    ("pipe x spigot", "pipe", "spigot", False, "BASE", 0.0),
    ("pipe x collar", "pipe", "collar", False, "BASE", 0.0),
    ("bore x spigot", "bore", "spigot", False, "T_BORE0", 0.0),
    ("bore x collar", "bore", "collar", False, "T_BORE0", 0.0),
]


def pair_threshold(theta_deg, fa, fb, symmetric, ext, n_grid, passes=3):
    """Largest axial reach of the overlap between two arm features at angle theta.

    THE CHART IS EXACT IN z AND REFINED IN (tA, tB). Both features are surfaces of revolution
    about their own axis, so a point is fixed by (tA, tB) up to the out-of-plane offset z, and
    each feature's radius band becomes an interval in z^2 that can be intersected in closed
    form. That removes a whole grid dimension AND the discretisation error along it; the two
    remaining axes are then refined three times about the coarse argmax, which lands the
    threshold within about 1e-4 mm instead of the 0.058 mm a single 481^3 pass gives.

    Sanity: two cylinders of radius R1 and R2 whose axes cross at theta overlap out to
    (R2 + R1 cos theta)/sin theta along axis A, and two equal ones out to R cot(theta/2) on the
    bisector. Both closed forms are asserted against this routine in calibrate().
    """
    th = math.radians(theta_deg)
    if abs(math.sin(th)) < 1e-9:
        # Collinear arms: no in-plane solution exists. Opposed arms (180 deg) cannot foul
        # each other's sockets, and the article has no repeated direction.
        return -1e9
    ct, st = math.cos(th), math.sin(th)
    rA0, rA1, _, _ = fa
    rB0, rB1, _, _ = fb
    tA0 = fa[2] if not isinstance(fa[2], str) else None
    tA1 = fa[3]
    tB0 = fb[2] if not isinstance(fb[2], str) else None
    tB1 = fb[3]

    lo_a, hi_a = -ext, ext
    lo_b, hi_b = -ext, ext
    best = -1e9
    best_a = best_b = 0.0
    for p in range(passes):
        ta = np.linspace(lo_a, hi_a, n_grid)
        tb = np.linspace(lo_b, hi_b, n_grid)
        TA, TB = np.meshgrid(ta, tb, indexing="ij")
        y = (TB - TA * ct) / st                     # in-plane offset perpendicular to arm A
        dB = TA * st - y * ct                       # in-plane offset perpendicular to arm B
        # z^2 windows each feature's radius band allows, intersected.
        loA = np.maximum(rA0 ** 2 - y * y, 0.0)
        hiA = rA1 ** 2 - y * y
        loB = np.maximum(rB0 ** 2 - dB * dB, 0.0)
        hiB = rB1 ** 2 - dB * dB
        ok = np.maximum(loA, loB) <= np.minimum(hiA, hiB)
        if tA0 is not None:
            ok &= TA >= tA0
        if tA1 is not None:
            ok &= TA <= tA1
        if tB0 is not None:
            ok &= TB >= tB0
        if tB1 is not None:
            ok &= TB <= tB1
        obj = np.minimum(TA, TB) if symmetric else TA
        obj = np.where(ok, obj, -1e9)
        idx = int(np.argmax(obj))
        val = float(obj.flat[idx])
        if val <= -1e8:
            if p == 0:
                return -1e9                       # the two features never meet at this angle
            break
        if val > best:
            best, best_a, best_b = val, float(TA.flat[idx]), float(TB.flat[idx])
        # Refine a box three cells wide about the argmax; the overlap region is a wedge at its
        # extreme point, never an isolated tangency, so there are always grid points inside.
        ha = 3.0 * (hi_a - lo_a) / (n_grid - 1)
        hb = 3.0 * (hi_b - lo_b) / (n_grid - 1)
        lo_a, hi_a = best_a - ha, best_a + ha
        lo_b, hi_b = best_b - hb, best_b + hb
    return best


def pair_chart(angles, prm, n_grid, ext=16.0):
    boxes = feature_boxes(prm)
    chart = {}
    for th in angles:
        row = {}
        for name, ka, kb, sym, comparand, bias in PAIR_TYPES:
            v = pair_threshold(th, boxes[ka], boxes[kb], sym, ext, n_grid)
            if v > -1e8:
                v += prm["shoulder"] if bias == "SHOULDER" else bias
            # null, not a sentinel: at this angle the two features never meet at all, and a
            # -1e9 in the report would be read as a measurement by anything downstream.
            row[name] = {"thresholdMm": None if v <= -1e8 else round(v, 4),
                         "comparand": comparand}
        # pipe against the node's own core: |P| <= core_r bounds tA at core_r regardless of
        # the pair angle, so it is closed form and does not need the chart.
        row["pipe x core"] = {"thresholdMm": round(prm["core_r"], 4), "comparand": "BASE"}
        chart[f"{th:.4f}"] = row
    return chart


def calibrate_pair_chart(prm):
    """Hold the chart to closed forms before anything is decided by it."""
    boxes = feature_boxes(prm)
    bad = []
    ro = prm["pipe_od"] / 2.0 + prm["clearance"]
    for th in (45.0, 60.0, 90.0, 120.0):
        want = ro / math.tan(math.radians(th / 2.0))
        got = pair_threshold(th, boxes["slot"], boxes["slot"], True, 16.0, 481)
        if abs(got - want) > 2e-3:
            bad.append(f"slot x slot at {th} deg: chart {got:.4f}, Ro*cot(theta/2) {want:.4f}")
    # Bare cylinders, no axial start: two of radius R1 and R2 crossing at theta overlap out to
    # (R2 + R1 cos theta)/sin theta along axis A. The bore's own t >= core_r*0.3 is dropped
    # here on purpose — this calibrates the geometry engine, not the feature.
    r_bore = boxes["bore"][1]
    cyl = (0.0, r_bore, None, None)
    for th in (45.0, 60.0, 90.0):
        want = (r_bore + r_bore * math.cos(math.radians(th))) / math.sin(math.radians(th))
        got = pair_threshold(th, cyl, cyl, False, 16.0, 481)
        if abs(got - want) > 2e-3:
            bad.append(f"bore x bore at {th} deg: chart {got:.4f}, closed form {want:.4f}")
    return bad


def pin_boxes_to_field(prm, rng):
    """Assert the feature boxes ARE the field, on a one-armed node, at 10^4 points each.

    The slot and the bore are subtracted from the finished field with a hard max(), so every
    point inside those boxes is exactly void — that half is an identity and catches a change of
    expression. The spigot and lip halves are weaker by construction: smooth-min only ever adds
    material (smin(a,b,k) <= min(a,b)), so a point inside them and outside every void must be
    solid. The outer bound uses the blend's own worst case, smin(a,a,k) = a - k/4.
    """
    d = np.array([0.0, 0.0, 1.0])
    arms, lands = [d], []
    base = prm["core_r"] + prm["shoulder"] + 4.0
    stubs, bores = [prm["stub"]], [prm["core_r"] * 0.3]
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]
    crest = spig_r + (prm["rib_h"] if prm["ribs"] else 0.0)
    ro_slot = prm["pipe_od"] / 2.0 + prm["clearance"]
    r_collar = prm["pipe_od"] / 2.0 + prm["lip_wall"]
    r_bore = spig_r - prm["spigot_wall"]
    t_bore0 = bores[0]
    e1, e2 = arm_frame(d)

    def cyl(n, r0, r1, t0, t1):
        r = np.sqrt(rng.uniform(r0 ** 2, r1 ** 2, n))
        a = rng.uniform(0.0, 2 * np.pi, n)
        t = rng.uniform(t0, t1, n)
        return t[:, None] * d + r[:, None] * (np.cos(a)[:, None] * e1 + np.sin(a)[:, None] * e2)

    k4 = prm["blend"] / 4.0          # smin(a, a, k) = a - k/4: the blend's whole reach
    cup = min(prm["lip"], prm["stub"])
    bad = []
    checks = [
        # OUTSIDE THE CREST, not outside the bare spigot: the slot is now cut to the ribbed
        # profile, so between spig_r and spig_r + rib_h the field is solid on a third of the
        # circumference by design. Sampling there would fire on the feature this version added.
        ("slot is void", cyl(10000, crest + 0.05, ro_slot - 0.05, base + 0.05,
                             base + prm["stub"] - 0.05), +1),
        ("bore is void", cyl(10000, 0.0, r_bore - 0.05, t_bore0 + 0.05,
                             base + prm["stub"] - 0.05), +1),
        # The spigot WALL, not the whole disc: the bore is subtracted out of its middle, so
        # sampling r < r_bore would be testing the bore box against the spigot box.
        ("spigot wall is solid", cyl(10000, r_bore + 0.05, spig_r - 0.05, 0.05, base - 0.05),
         -1),
        # The collar: solid below the seat over the pipe's own footprint, and solid outside the
        # slot's outer wall for the depth of the cup.
        ("seat is solid", cyl(10000, r_bore + 0.05, r_collar - 0.05,
                              base - prm["shoulder"] + 0.05, base - 0.05), -1),
        ("cup is solid", cyl(10000, ro_slot + 0.05, r_collar - 0.05, base + 0.05,
                             base + cup - 0.05), -1),
    ]
    far = cyl(20000, r_collar + k4 + 0.5, r_collar + k4 + 8.0, 0.05, base + cup - 0.05)
    far = far[np.linalg.norm(far, axis=1) > prm["core_r"] + k4 + 0.5]   # outside the core ball
    checks.append(("nothing beyond the collar and the core", far, +1))
    for label, P, want in checks:
        s = node_sdf(P, arms, lands, prm, False, base, stubs, bores)
        wrong = int((s * want < 0).sum())
        if wrong:
            bad.append(f"feature box '{label}' disagrees with node_sdf at {wrong} of "
                       f"{len(P)} points — the box expressions no longer describe the field")
    if smin(np.array([0.0]), np.array([0.0]), prm["blend"])[0] != -k4:
        bad.append("smin(0, 0, k) != -k/4 — the blend reach used by the outer bound is wrong")
    return bad


# ------------------------------------------------------------------------- field sampling --
# Every resolution below is justified against a physical length: the 0.150 mm radial fit gap,
# the 0.250 mm rib, the ~0.4 mm surviving bearing ring, and the 0.206 mm slot-margin surplus on
# the 12-arm node. MIDPOINT RULE, ALWAYS: rectangle-rule polar sampling with the endpoints
# included biases area high by half a cell at each end and reported the 12-arm node's seat as
# 28.88 mm2, which is 102.1% of a 28.274 mm2 annulus and impossible. With midpoints the same
# node returns 28.2743 at every grid from 32x128 to 256x1024, and that exactness is the
# calibration: an implementation that misses it is sampling wrong and its verdict on the other
# 431 ends is worthless.
BEAR_HI = (64, 256)        # 0.0156 mm radial x 0.11 mm arc; +/- 0.01 mm2 vs 256x1024
BEAR_LO = (32, 128)        # the crush curve's shape only, +/- 0.05 mm2
BEAR_DT = (0.02, 0.10, 0.25, 0.50, 1.0, 2.0, 3.0, 4.0)
SECTION = (176, 256)       # 0.025 mm radial; +/- 0.15 mm2 against 35.814 x wrap
WRAP_AZ, WRAP_T = 720, 8   # 0.0031 mm arc at r = 3.50; must match the closed form to 2 cells
RIB_AZ, RIB_T = 360, 3
LIP_NR, LIP_AZ = 11, 360
SEAT_GRID = (24, 96)       # a bracket, not an integral: solid below base, void above
# The insertion sweep's pipe: radial x axial x azimuth over the pipe's OWN annulus, r from
# pipe_id/2 to pipe_od/2. The old (1, 20, 24) sampled a zero-thickness cylinder at the BORE
# only, so the surface that actually sets a peg-in-hole limit — the pipe's outside against the
# slot's outer wall at pipe_od/2 + clearance — was never in the point set. Refining it is a
# measurement, not a preference: (1,20,24), (1,28,36), (2,20,24), (2,28,36), (3,40,48),
# (4,56,72) and (5,80,96) all report the same 19.75 mm of engagement at the peg-in-hole limit
# and the same 0.00 mm at the 34.87 deg a closing member needs, and cost 0.4 to 75 s. So the
# figure was already converged and the refinement buys coverage rather than accuracy: two radii
# put the OD in the test, and (28, 36) keeps the sweep under two seconds.
#
# What this grid does NOT do is adjudicate the 0.15 mm fit — 0.87 mm of axial step and 0.87 mm
# of arc at r = 5 are six times coarser than that. It resolves a JAM. The clearance itself is
# decided in closed form by P8 and measured at 0.11 mm of arc by the bearing annulus.
SWEEP_NR, SWEEP_AX, SWEEP_AZ = 2, 28, 36
SDF_PROBE_MM = 0.5         # P15's grid: a plug is 8 mm across, a burr is not what this asks


def rib_radii(prm):
    """Radii to sign-test across the crush rib, DERIVED and not typed.

    The list used to be (3.84 ... 4.10), which is the right ladder for a 8 mm bore and a
    0.25 mm rib and meaningless for any other: change rib_h and the probe stops straddling the
    crest, change pipe_id and it misses the spigot entirely. It also stopped AT the crest, so
    once the slot was cut to the rib profile there was no radius outside the rib left to check
    the converse on, and that clause would have gone vacuously true the day the fix landed.
    Three bands now: inside the spigot, across the rib, and outside the crest.
    """
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]
    crest = spig_r + prm["rib_h"]
    ro_slot = prm["pipe_od"] / 2.0 + prm["clearance"]
    band = [spig_r + f * prm["rib_h"] for f in (0.05, 0.25, 0.5, 0.8, 0.96)]
    return tuple(sorted({round(r, 4) for r in
                         [spig_r - 0.01, spig_r] + band
                         + [crest, crest + 0.01, crest + 0.05, ro_slot - 0.05]}))


def polar_points(axis, t, r0, r1, nr, na):
    """Midpoint polar sample of an annulus normal to `axis` at station t."""
    e1, e2 = arm_frame(axis)
    dr = (r1 - r0) / nr
    dphi = 2 * np.pi / na
    rr = r0 + (np.arange(nr) + 0.5) * dr
    pp = (np.arange(na) + 0.5) * dphi
    Rg, Pg = np.meshgrid(rr, pp, indexing="ij")
    P = (t * axis + Rg[..., None] * (np.cos(Pg)[..., None] * e1
                                     + np.sin(Pg)[..., None] * e2))
    return P.reshape(-1, 3), Rg, dr, dphi


def ring_points(axis, t, r, na):
    e1, e2 = arm_frame(axis)
    a = (np.arange(na) + 0.5) * (2 * np.pi / na)
    return t * axis + r * (np.cos(a)[:, None] * e1 + np.sin(a)[:, None] * e2)


def probe_node(u, g, prm):
    """One batched node_sdf call per rib setting, covering every probe on every arm.

    Cost is linear in points x arms either way — batching buys numpy overhead only, but that is
    about 30% at these sizes. Sampling is float32: the field is smooth at the millimetre scale,
    a float32 zero crossing is placed to ~4e-6 mm, and the finest cell here is 0.0156 mm. Area
    is accumulated in float64 from the float32 sign, and the 28.2743 calibration holds in both.
    """
    inf = g["info"][u]
    base, arms, lands = inf["base"], inf["armsPrint"], inf["landsPrint"]
    is_hub = inf["role"] == "hexHub"
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]
    ro_slot = prm["pipe_od"] / 2.0 + prm["clearance"]
    r_collar = prm["pipe_od"] / 2.0 + prm["lip_wall"]

    batches = {0: [], prm["ribs"]: []}      # points needing ribs off / ribs as configured
    plan = []
    for ai, axis in enumerate(arms):
        # EVERY STATION IN THE ENGAGED LENGTH IS A FRACTION OF IT, never a fixed offset from
        # base. A closing end is engaged 2 mm, so `base + stub - 2` — the old section station —
        # lands exactly on the seat plane and measures the collar's full disc instead of the
        # spigot. Fractions measure the same relative places on both engagements.
        stub = inf["stubs"][ai]

        def add(ribs, pts, tag, meta=None, ai=ai):
            batches[ribs].append(pts)
            plan.append((ribs, ai, tag, len(pts), meta))

        for si, dt in enumerate(BEAR_DT):
            nr, na = BEAR_HI if si < 2 else BEAR_LO
            P, Rg, dr, dphi = polar_points(axis, base - dt, 4.0, 5.0, nr, na)
            add(0, P, f"bear{si}", (Rg, dr, dphi, nr, na))
        P, Rg, dr, dphi = polar_points(axis, base - BEAR_DT[0], 4.0, 5.0, *BEAR_HI)
        add(prm["ribs"], P, "bearRib", (Rg, dr, dphi) + BEAR_HI)

        ts = base + stub * np.linspace(0.1, 0.9, WRAP_T)
        add(0, np.vstack([ring_points(axis, t, 3.50, WRAP_AZ) for t in ts]), "wrap")

        rib_ts = base + stub * np.linspace(0.1, 0.9, RIB_T)
        rib_r = rib_radii(prm)
        rib_pts = np.vstack([ring_points(axis, t, r, RIB_AZ) for t in rib_ts for r in rib_r])
        add(prm["ribs"], rib_pts, "ribBand")
        # The converse: ribs on and ribs off must give the same field everywhere outside the
        # crest, and a DIFFERENT one inside it — which is exactly what the fix was. Cheaper
        # grid, sign test only.
        conv = np.vstack([ring_points(axis, t, r, 120) for t in rib_ts for r in rib_r])
        add(0, conv, "ribConv")

        lip_r = np.linspace(ro_slot, r_collar, LIP_NR)
        # In the cup, above the seat, which is where the pipe is; and in the collar below the
        # seat, which is where the cup's material comes from. The first is the anti-brooming
        # feature doing its job and the second is only the seat's own outer ring.
        add(0, np.vstack([ring_points(axis, base + min(prm["lip"], stub) * 0.5, r, LIP_AZ)
                          for r in lip_r]), "lipSeat")
        add(0, np.vstack([ring_points(axis, base - prm["shoulder"] * 0.5, r, LIP_AZ)
                          for r in lip_r]), "lipHome")

        P, Rg, dr, dphi = polar_points(axis, base + 0.75 * stub, 0.0,
                                       spig_r + prm["rib_h"] + 0.3, *SECTION)
        add(0, P, "section", (Rg, dr, dphi) + SECTION)
        P, Rg, dr, dphi = polar_points(axis, base + 0.25 * stub, 0.0,
                                       spig_r + prm["rib_h"] + 0.3, *SECTION)
        add(0, P, "sectionRoot", (Rg, dr, dphi) + SECTION)

        # ABOVE THE CREST. The seat bracket asks "solid just below base, void just above it",
        # and the crush ribs are solid above base by design — they are the interference the
        # pipe grips. Sampling from pipe_id/2 would report every end as never releasing the
        # pipe, which is a statement about the rib and not about the seat.
        add(prm["ribs"], polar_points(axis, base - 0.005, 4.0, 5.0, *SEAT_GRID)[0], "seatBelow")
        add(prm["ribs"], polar_points(axis, base + 0.005, spig_r + prm["rib_h"], 5.0,
                                      *SEAT_GRID)[0], "seatAbove")

    out = {}
    for ribs, chunks in batches.items():
        if not chunks:
            continue
        P = np.vstack(chunks).astype(np.float32)
        p = dict(prm)
        p["ribs"] = ribs
        s = node_sdf(P, [a.astype(np.float32) for a in arms],
                     [n.astype(np.float32) for n in lands], p, is_hub, base,
                     inf["stubs"], inf["bores"],
                     land_offs=inf["offs"], post_axis=inf["postPrint"])
        out[ribs] = s
    cursor = {k: 0 for k in out}
    result = collections.defaultdict(dict)
    for ribs, ai, tag, n, meta in plan:
        s = out[ribs][cursor[ribs]:cursor[ribs] + n]
        cursor[ribs] += n
        result[ai][tag] = (s, meta)
    return result


def reduce_probe(res, prm, base, wrap, axis, bend_n):
    """Turn one arm's raw sign arrays into the numbers the certificate carries.

    `bend_n` is the unit vector, in the PRINT frame, along which the film's line load pushes
    this member — the fibre direction its moment actually bends the section about. None where
    no panel drains to the member and the moment is zero.
    """
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]
    out = {}

    def area(tag):
        s, (Rg, dr, dphi, nr, na) = res[tag]
        return float(((s < 0).reshape(nr, na) * Rg).sum() * dr * dphi)

    profile = [round(area(f"bear{i}"), 4) for i in range(len(BEAR_DT))]
    out["bearingProfileMm2"] = profile
    out["bearingAreaAt20umMm2"] = profile[0]
    out["bearingAreaAt100umMm2"] = profile[1]
    out["ribShelfAreaMm2"] = round(area("bearRib") - profile[0], 4)
    sat = wrap * math.pi * (25.0 - 16.0)
    out["bearingAreaSatMm2"] = round(sat, 4)
    # Embedment to saturation: the first station whose area reaches 99% of the wrap-limited
    # annulus, interpolated between stations. This is how far the pipe must crush in before it
    # bears on everything it is ever going to bear on.
    embed = None
    for i in range(len(BEAR_DT)):
        if profile[i] >= 0.99 * sat and sat > 1e-9:
            if i == 0:
                embed = BEAR_DT[0]
            else:
                lo, hi = profile[i - 1], profile[i]
                f = 0.0 if hi <= lo else (0.99 * sat - lo) / (hi - lo)
                embed = BEAR_DT[i - 1] + f * (BEAR_DT[i] - BEAR_DT[i - 1])
            break
    out["embedToSatMm"] = round(embed, 4) if embed is not None else None
    out["embedToSatReached"] = embed is not None

    s, _ = res["wrap"]
    out["fitAzFrac"] = round(float((s < 0).mean()), 5)

    rib_r = rib_radii(prm)
    crest = spig_r + prm["rib_h"]
    s, _ = res["ribBand"]
    band = (s < 0).reshape(RIB_T, len(rib_r), RIB_AZ)
    live = [bool(band[:, j, :].any()) for j in range(len(rib_r))]
    out["ribBandSolidByRadius"] = {f"{rib_r[j]:.3f}": bool(live[j]) for j in range(len(rib_r))}
    # r = spig_r exactly is a knife edge in floating point — the spigot surface itself — so it
    # decides nothing, and so is r = crest. The outermost solid radius is taken from the
    # strictly-outside probes and falls back to the nominal spigot surface when none is solid,
    # which is why a measured interference is always one probe step inside the crest.
    outer = [rib_r[j] for j in range(len(rib_r)) if live[j] and rib_r[j] > spig_r + 1e-9]
    out["maxSolidRadiusMm"] = round(max(outer) if outer else spig_r, 4)
    out["ribLive"] = bool(outer)
    out["ribInterferenceMm"] = round(out["maxSolidRadiusMm"] - prm["pipe_id"] / 2.0, 4)

    s0, _ = res["ribConv"]
    s3 = res["ribBand"][0]
    conv3 = (s3 < 0).reshape(RIB_T, len(rib_r), RIB_AZ)[:, :, ::3]
    conv0 = (s0 < 0).reshape(RIB_T, len(rib_r), 120)
    outside = [j for j in range(len(rib_r)) if rib_r[j] > crest + 1e-9]
    inside = [j for j in range(len(rib_r)) if spig_r + 1e-9 < rib_r[j] < crest - 1e-9]
    out["ribSignAgreesOutsideCrest"] = bool(
        np.array_equal(conv3[:, outside, :], conv0[:, outside, :]))
    # And the signature of the fix itself: inside the crest band the ribbed field must be
    # solid where the ribless one is void. If those two agree the slot has eaten the rib again.
    out["ribAddsMaterialInBand"] = bool(
        inside and (conv3[:, inside, :] & ~conv0[:, inside, :]).any())

    s, _ = res["lipSeat"]
    out["lipAnnulusSolidFracAtSeat"] = round(float((s < 0).mean()), 4)
    s, _ = res["lipHome"]
    out["lipAnnulusSolidFracAtHome"] = round(float((s < 0).mean()), 4)
    # MEASURED, not derived from base < core_r + lip. That expression was right about the V2
    # part and is meaningless about this one: the cup is driven off `base` now, so whether it
    # reaches the pipe is a question about material above the seat and the field is what
    # answers it. The comparand is the socket's own wrap, because a land that cuts the socket
    # in half cuts the cup in half with it and half a cup is still a cup.
    out["lipReachesPipe"] = bool(out["lipAnnulusSolidFracAtSeat"] >= 0.5 * wrap)

    out["spigotAreaMm2"] = round(area("section"), 4)
    out["spigotAreaAtRootMm2"] = round(area("sectionRoot"), 4)

    s, _ = res["seatBelow"]
    below = bool((s < 0).any())
    s, _ = res["seatAbove"]
    above = bool((s < 0).any())
    out["seatSolidBelowBase"] = below
    out["seatSolidAboveBase"] = above
    out["tSeatMm"] = round(base, 4) if (below and not above) else None
    out["tSeatToleranceMm"] = 0.005

    # Second moments of the surviving spigot section, measured on the same grid the area came
    # off, and the section modulus about the axis the demand ACTUALLY bends it about.
    #
    # A section modulus is I about an axis divided by the distance to the furthest fibre from
    # that axis, so both halves have to be measured about the SAME direction. Writing the fibre
    # direction as n = (cos t, sin t) in the arm's own frame,
    #     I(t) = Iyy cos^2 t + 2 Ixy cos t sin t + Ixx sin^2 t     and     c(t) = max |r . n|,
    # and Z(t) = I(t)/c(t). The principal directions are the extrema of I(t), at
    # t* = 0.5 atan2(2 Ixy, Iyy - Ixx). The earlier expression used atan2(2 Ixy, Ixx - Iyy),
    # which is the MIRROR of that direction: i1 and i2 are eigenvalues and survived it, but c1
    # and c2 did not, and 48 rimVertex spoke ends published Zmax 26.98 / Zmin 4.20 for a section
    # congruent with 96 others publishing 21.29 / 9.13. calibrate() now holds congruent sections
    # to each other and to the analytic half-annulus, so that cannot come back silently.
    s, (Rg, dr, dphi, nr, na) = res["section"]
    solid = (s < 0).reshape(nr, na)
    pp = (np.arange(na) + 0.5) * dphi
    X = Rg * np.cos(pp)[None, :]
    Y = Rg * np.sin(pp)[None, :]
    dA = Rg * dr * dphi
    m0 = float((solid * dA).sum())
    if m0 > 1e-9:
        cx = float((solid * X * dA).sum()) / m0
        cy = float((solid * Y * dA).sum()) / m0
        xs, ys = X - cx, Y - cy
        Ixx = float((solid * ys * ys * dA).sum())
        Iyy = float((solid * xs * xs * dA).sum())
        Ixy = float((solid * xs * ys * dA).sum())
        pts = np.stack([xs[solid], ys[solid]], 1)

        def modulus(t):
            n = np.array([math.cos(t), math.sin(t)])
            i_t = (Iyy * n[0] ** 2 + 2.0 * Ixy * n[0] * n[1] + Ixx * n[1] ** 2)
            c_t = float(np.abs(pts @ n).max())
            return i_t, c_t, (i_t / c_t if c_t > 1e-9 else 0.0)

        t_star = 0.5 * math.atan2(2.0 * Ixy, Iyy - Ixx)
        i1, c1, z1 = modulus(t_star)
        i2, c2, z2 = modulus(t_star + math.pi / 2.0)
        out["spigotIMaxMm4"] = round(max(i1, i2), 4)
        out["spigotIMinMm4"] = round(min(i1, i2), 4)
        out["cMaxMm"] = round(max(c1, c2), 4)
        out["spigotZMaxMm3"] = round(z1 if i1 >= i2 else z2, 4)
        out["spigotZMinMm3"] = round(z2 if i1 >= i2 else z1, 4)
        out["spigotPrincipalCheckMm4"] = round(
            abs((i1 + i2) - (Ixx + Iyy)) + abs(max(i1, i2)
                                               - ((Ixx + Iyy) / 2.0
                                                  + math.hypot((Ixx - Iyy) / 2.0, Ixy))), 6)
        if bend_n is None:
            out["bendingFibreDeg"] = None
            out["spigotZAtDemandMm3"] = None
            out["spigotCAtDemandMm"] = None
        else:
            e1, e2 = arm_frame(axis)
            t_d = math.atan2(float(bend_n @ e2), float(bend_n @ e1))
            i_d, c_d, z_d = modulus(t_d)
            out["bendingFibreDeg"] = round(math.degrees(t_d) % 180.0, 3)
            out["spigotZAtDemandMm3"] = round(z_d, 4)
            out["spigotCAtDemandMm"] = round(c_d, 4)
    else:
        out.update({"spigotIMaxMm4": 0.0, "spigotIMinMm4": 0.0, "cMaxMm": 0.0,
                    "spigotZMaxMm3": 0.0, "spigotZMinMm3": 0.0,
                    "spigotPrincipalCheckMm4": 0.0, "bendingFibreDeg": None,
                    "spigotZAtDemandMm3": None, "spigotCAtDemandMm": None})
    return out


def measure_walls(u, ai, g, prm):
    """minWallMm from the field, by radial section, never read off a parameter.

    The two walls that exist in a socket are the spigot's (bore to spigot surface) and the
    lip's (slot's outer radius to the lip's outer radius). lip_wall is 1.6 mm in argparse and
    1.45 mm in the part, because the slot's outer radius is pipe_od/2 + clearance and the lip's
    is pipe_od/2 + lip_wall. Recording the count of extrusion widths makes a fractional one
    visible: 1.45 / 0.6 is 2.42 perimeters, which no slicer lays.

    Measured PER ARM CLASS, not on arm 0 and copied. The earlier version measured arm 0 and
    asserted in a docstring that every arm of a node is cut from the same parameters — true of
    the parameters, not of the part, because a mating land opens 216 of the 432 sockets and the
    surviving wall of an opened socket is a different measurement. main() now measures one arm
    per (wrap, coplanar-land-count) group on each node and copies only within the group, so the
    uniformity claim is tested where it is cheap and dropped where it is not.

    The thickness is the MEDIAN radial solid run through the wall over azimuth, not the
    smallest — the smallest is the knife edge where a land slices through, which is a land
    artefact and not a wall a slicer ever lays.
    """
    inf = g["info"][u]
    base, arms, lands = inf["base"], inf["armsPrint"], inf["landsPrint"]
    axis = arms[ai]
    step = 0.01
    stub = inf["stubs"][ai]
    spig_r = prm["pipe_id"] / 2.0 - prm["clearance"]
    r_bore = spig_r - prm["spigot_wall"]
    ro_slot = prm["pipe_od"] / 2.0 + prm["clearance"]
    r_lip = prm["pipe_od"] / 2.0 + prm["lip_wall"]
    walls = {}
    for label, t, r0, r1, ref in (
            ("spigot", base + stub / 2.0, 0.0, spig_r + 1.0, (r_bore + spig_r) / 2.0),
            ("lip", base + min(prm["lip"], stub) / 2.0, ro_slot - 1.0, r_lip + 1.0,
             (ro_slot + r_lip) / 2.0)):
        rr = np.arange(r0, r1, step)
        P = np.vstack([ring_points(axis, t, r, 64) for r in rr]).astype(np.float32)
        s = field(P, inf, prm).reshape(len(rr), 64) < 0
        i_ref = int(np.argmin(np.abs(rr - ref)))
        runs = []
        for j in range(64):
            col = s[:, j]
            if not col[i_ref]:
                continue
            lo = hi = i_ref
            while lo > 0 and col[lo - 1]:
                lo -= 1
            while hi < len(rr) - 1 and col[hi + 1]:
                hi += 1
            runs.append((hi - lo + 1) * step)
        # Median, not min or max. The max hides behind a crush rib, which is 0.25 mm of extra
        # radius on a third of the circumference and not a wall. The min is the knife edge
        # where a mating land slices through the socket, which is a land artefact. The median
        # is the thickness the slicer lays around most of the circumference.
        walls[label] = round(float(np.median(runs)), 4) if runs else 0.0
    return walls


# ------------------------------------------------------------- assembled-article collision --
def seg_seg_dist(P1, Q1, P2, Q2):
    """Vectorised segment-to-segment distance, broadcasting over leading axes."""
    d1, d2, r = Q1 - P1, Q2 - P2, P1 - P2
    a = (d1 * d1).sum(-1)
    e = (d2 * d2).sum(-1)
    f = (d2 * r).sum(-1)
    c = (d1 * r).sum(-1)
    b = (d1 * d2).sum(-1)
    den = a * e - b * b
    s = np.where(den > 1e-9, np.clip((b * f - c * e) / np.where(den > 1e-9, den, 1.0), 0, 1), 0.0)
    t = np.clip((b * s + f) / e, 0, 1)
    s = np.clip((b * t - c) / a, 0, 1)
    return np.linalg.norm((P1 + s[..., None] * d1) - (P2 + t[..., None] * d2), axis=-1)


def pipe_segments(g, radius_of=None):
    """Every seated pipe, SHOULDER FACE TO SHOULDER FACE, with its own outer radius.

    Never node centre to node centre. Adjacent members share a centre, so centre-to-centre
    reports every neighbour as a collision and concludes 0 of 216 pipes can be placed — a
    catastrophe that is pure modelling error. Each end is trimmed by its own node's base.

    The radius is PER MEMBER because the article is not one SKU. stock_build specifies 14 x 12
    for the 36 rim members and 10 x 8 for the other 180, which P4 has frozen at 72 wrong-SKU
    ends since the day it was written; modelling every member at 10 mm made P9 pass on a pipe
    the analysis does not buy. `radius_of` is a callable taking (a, b, family).
    """
    S, Q, R = [], [], []
    for a, b, fam in g["members"]:
        pa = g["pos"][a]
        pb = g["pos"][b]
        d = pb - pa
        L = np.linalg.norm(d)
        un = d / L
        S.append(pa + un * g["info"][a]["base"])
        Q.append(pb - un * g["info"][b]["base"])
        R.append(5.0 if radius_of is None else radius_of(a, b, fam))
    return np.array(S), np.array(Q), np.array(R)


def fib_dirs(n):
    i = np.arange(n) + 0.5
    phi = np.arccos(1.0 - 2.0 * i / n)
    th = np.pi * (1.0 + 5.0 ** 0.5) * i
    return np.stack([np.cos(th) * np.sin(phi), np.sin(th) * np.sin(phi), np.cos(phi)], 1)


def escape_scan(S, Q, R, subject, others, dirs, lam):
    """This pipe's straight-line direction out, against the geometry present — or None.

    Returns the FIRST verified escape direction rather than a bare boolean, because the
    direction is not bookkeeping: it is the insertion line, reversed. The page's assembly
    animation flies each member in along it, so the approach the viewer watches is the
    same line this proof certified clear — an animation that clipped through placed
    members was drawing a motion nobody proved. Truthiness is unchanged for callers that
    only ask WHETHER (an ndarray is truthy here and None is not), but comparisons must be
    `is None`, never `not`, which numpy refuses on a vector.

    Two stages, and the coarse one is a NECESSARY condition rather than an approximation: the
    minimum over a subset of stations can only be larger than the minimum over all of them, so
    a direction that already fouls at every tenth station fouls, full stop. Members that HAVE
    an escape find it in the first few directions; members that do not have to try all of them,
    and against the finished article there are 108 of those. Rejecting them coarsely first is
    what keeps this advisory in seconds rather than half a minute.

    The clearance is R[subject] + R[other], per PAIR, so a 14 mm rim member is asked to clear
    the 10 mm tie it actually meets rather than the 10 mm one the old single --pipe-od pretended
    every member was.
    """
    if len(others) == 0:
        return dirs[0]                     # nothing placed: every direction is an escape
    axis = Q[subject] - S[subject]
    axis = axis / np.linalg.norm(axis)
    ok = dirs[np.abs(dirs @ axis) < 0.35]
    clear = R[subject] + R[others]                      # (n_others,), broadcast on the last axis
    coarse = lam[::10]
    P2 = S[others][None, None, :, :]
    Q2 = Q[others][None, None, :, :]
    off = coarse[None, :, None] * ok[:, None, :]
    P1 = (S[subject] + off)[:, :, None, None, :]
    Q1 = (Q[subject] + off)[:, :, None, None, :]
    gap = seg_seg_dist(P1, Q1, P2, Q2) - clear
    survivors = ok[gap.min(axis=(1, 2, 3)) >= 0.0]
    for d in survivors:
        P1 = (S[subject][None, :] + lam[:, None] * d)[:, None, None, :]
        Q1 = (Q[subject][None, :] + lam[:, None] * d)[:, None, None, :]
        if (seg_seg_dist(P1, Q1, P2, Q2) - clear).min() >= 0.0:
            return d
    return None


# ----------------------------------------------------------------- insertion kinematics --
def pilot_bound(P, diametral):
    """s_max = 0.75 (2D)^(2/3) P^(1/3), the deepest pilot a closing member can swing in on.

    Two constraints bound the path of a member that must drop between two nodes already in
    place. The kinematic identity e_A + e_B = s_A + s_B - P(1 - cos phi) says how much
    engagement the tilt buys back, and the peg-in-hole limit e <= D/phi says how deep a tilted
    spigot can be before it jams. Feasibility at every phi needs 2s <= 2D/phi + P phi^2/2;
    minimising the right-hand side over phi gives phi* = (2D/P)^(1/3) and the closed form
    above. Verified against a 400,000-point sweep of phi in calibrate().

    The published form 0.94494 (2c)^(2/3) (P/2)^(1/3) is wrong by 2^(2/3) = 1.587 — it returns
    2.04 where this returns 3.234 — even though the numbers printed beside it were right.
    """
    return 0.75 * (2.0 * diametral) ** (2.0 / 3.0) * P ** (1.0 / 3.0)


def phi_star(P, diametral):
    return (2.0 * diametral / P) ** (1.0 / 3.0)


# ------------------------------------------------------------ connectivity, without scipy --
def _spread(mask, seed, axis):
    """One run-fill pass: any maximal run of `mask` along `axis` that a seed touches fills.

    Cell-by-cell dilation would need one pass per cell of travel — a thousand passes to cross a
    1025-cell land, which is minutes. Filling whole runs at a time crosses the same shape in as
    many passes as the shape has turns, which is a handful.
    """
    m = np.moveaxis(mask, axis, -1)
    s = np.moveaxis(seed, axis, -1)
    pad = np.zeros_like(m[..., :1])
    starts = m & ~np.concatenate([pad, m[..., :-1]], axis=-1)
    rid = np.cumsum(starts, axis=-1)
    lines = int(np.prod(m.shape[:-1])) if m.ndim > 1 else 1
    stride = int(rid.max()) + 1
    key = rid + np.arange(lines).reshape(m.shape[:-1] + (1,)) * stride
    key = np.where(m, key, -1)
    flat = key.ravel()
    sel = flat >= 0
    hits = np.bincount(flat[sel], weights=s.ravel()[sel].astype(np.float64),
                       minlength=lines * stride) > 0
    out = np.zeros(m.shape, bool)
    out.ravel()[sel] = hits[flat[sel]]
    return np.moveaxis(out, -1, axis)


def flood(mask, seed):
    while True:
        new = seed.copy()
        for ax in range(mask.ndim):
            new |= _spread(mask, new, ax)
        if np.array_equal(new, seed):
            return seed
        seed = new


def border_reachable(mask):
    """Every True cell connected to the array border.

    scipy is not a declared dependency of this repository (requirements.txt lists websockets,
    numpy and Pillow, and says so on purpose), so this replaces ndimage.label with a run-fill.
    Same answer, one fewer thing to install.
    """
    seed = np.zeros_like(mask)
    for ax in range(mask.ndim):
        for i in (0, -1):
            s = [slice(None)] * mask.ndim
            s[ax] = i
            seed[tuple(s)] = mask[tuple(s)]
    return flood(mask, seed)


def count_components(mask):
    """Number of 4/6-connected components, at full resolution — coarsening merges real ones."""
    rest = mask.copy()
    n = 0
    while rest.any():
        seed = np.zeros_like(rest)
        seed[tuple(np.argwhere(rest)[0])] = True
        comp = flood(rest, seed)
        rest &= ~comp
        n += 1
    return n


def convex_hull_mask(solid, X, Y):
    """Monotone-chain hull of the solid silhouette, rasterised back onto the same grid."""
    pts = np.stack([X[solid], Y[solid]], 1)
    pts = np.unique(np.round(pts, 6), axis=0)
    order = np.lexsort((pts[:, 1], pts[:, 0]))
    pts = pts[order]

    def turn(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    def half(ps):
        out = []
        for p in ps:
            while len(out) >= 2 and turn(out[-2], out[-1], p) <= 0:
                out.pop()
            out.append(p)
        return out

    hull = np.array(half(list(pts))[:-1] + half(list(pts[::-1]))[:-1])
    inside = np.ones(X.shape, bool)
    for i in range(len(hull)):
        a, b = hull[i], hull[(i + 1) % len(hull)]
        inside &= ((b[0] - a[0]) * (Y - a[1]) - (b[1] - a[1]) * (X - a[0])) >= -1e-9
    return inside


def land_maps(u, li, g, prm, half, n, depths):
    """Silhouette of the solid on one land plane, at a list of signed depths INSIDE it.

    The plane is the OFFSET land — P.n = off in the print frame, the nominal cell face the
    part is truncated at — so depth 0 is the face itself, where the sunken article presents
    its post flat, and a negative depth samples outside the face where nothing may stand."""
    inf = g["info"][u]
    nrm = inf["landsPrint"][li]
    off = inf["offs"][li]
    ref = np.array([0.0, 0.0, 1.0]) if abs(nrm[2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    f1 = np.cross(nrm, ref)
    f1 /= np.linalg.norm(f1)
    f2 = np.cross(nrm, f1)
    gg = np.linspace(-half, half, n)
    cell = (gg[1] - gg[0]) ** 2
    X, Y = np.meshgrid(gg, gg, indexing="ij")
    out = []
    for dep in depths:
        P = (X[..., None] * f1 + Y[..., None] * f2
             + (off - dep) * nrm).reshape(-1, 3).astype(np.float32)
        out.append((field(P, inf, prm) < 0).reshape(n, n))
    return out, X, Y, cell


