# THE FRICTION COEFFICIENT NOBODY HAS MEASURED, used as a ceiling and never as a value. No dry
# sliding pair of a printed thermoplastic on a wound carbon tube reaches unity, so mu = 1 is
# above anything a bench test could return. It is here so that the dry-capture verdict below
# does not depend on a number this repository does not have: where the demand beats even this,
# the answer is settled, and where it does not, nothing has been shown and the row says so.
MU_BOUND = 1.0


def rib_contact_area(prm, spig_r, engagement, wrap):
    """Arc of crush rib actually pressed into the pipe bore, times the engaged length.

    The crest gen_nodes draws is spig_r + rib_h*max(cos(n*theta), 0) and the bore sits at
    spig_r + clearance, so a rib touches only where rib_h*cos(n*theta) > clearance: an arc of
    2*acos(clearance/rib_h)/n per rib, not the whole lobe and nowhere near the circumference.
    At the shipped 0.25 mm rib against a 0.15 mm clearance that is 35.4 deg per rib and 29.5%
    of the bore — which is why this area comes out a tenth of the bond area at the same end,
    and why quoting "the fit" as if the whole spigot gripped would have been wrong by 3.4x.

    Times wrap, because a mating land cuts the spigot's circumference away and takes whatever
    ribs stood in it with them; bond_area is scaled the same way for the same reason.
    """
    if not prm["ribs"] or prm["rib_h"] <= prm["clearance"]:
        return 0.0                      # no rib stands proud of the fit: nothing is gripped
    half_arc = math.acos(prm["clearance"] / prm["rib_h"]) / prm["ribs"]
    return 2.0 * half_arc * prm["ribs"] * spig_r * engagement * wrap


def margin(demand, demand_unit, demand_source, capacity, capacity_unit,
           capacity_source, kind, bound=None, experiment=None):
    """A margin is an object, never a bare number: what pushed, what holds, and who says so.

    `bound` IS THE HONESTY VALVE, and it exists because three of these load paths have no
    measured capacity and never will until someone runs a test. A number that is only a BOUND
    on the capacity may decide the margin in one direction and must not be allowed to decide it
    in the other:

      bound=None    a capacity. PASS or FAIL, as before.
      bound="upper" the most this path could possibly hold, every term taken generously. If the
                    demand beats it the FAIL is proven and no measurement can undo it; if it
                    does not, nothing has been shown and the verdict is UNPROVEN, never PASS.
      bound="lower" a floor under the capacity. Clearing a floor is a proven PASS; falling short
                    of one is not a failure, so that way the verdict is UNPROVEN too. Nothing in
                    the table uses it today — it is here because the rule is symmetric and the
                    next capacity anyone derives is as likely to be a floor as a ceiling.

    Without this the only two honest options were to invent a capacity or to leave 888 rows
    UNSOURCED, and both of those hide work that has actually been done. `experiment` is the
    test that would convert an UNSOURCED or UNPROVEN row into a real one; it is required on
    every row that lands in either, because "we don't know" without "and here is how to find
    out" is where this bill has been parked for two design generations.
    """
    # NO DEMAND outranks UNSOURCED: an end with no moment on it is not owed a bending capacity,
    # and calling that "unsourced" pads the census with 216 rows nobody has to go and find.
    if demand is None:
        verdict, m = "NOT DERIVED", None
    elif demand == 0.0:
        verdict, m = "NO DEMAND", None
    elif capacity is None:
        verdict, m = "UNSOURCED", None
    else:
        m = capacity / demand
        if bound is None:
            verdict = "PASS" if m >= 1.0 else "FAIL"
        elif bound == "upper":
            verdict = "FAIL" if m < 1.0 else "UNPROVEN"
        elif bound == "lower":
            verdict = "PASS" if m >= 1.0 else "UNPROVEN"
        else:
            raise ValueError(f"margin bound must be None, 'upper' or 'lower', not {bound!r}")
    if verdict in ("UNSOURCED", "UNPROVEN") and not experiment:
        raise ValueError(f"a {verdict} margin has to name the experiment that would settle it")
    return {"demand": demand, "demandUnit": demand_unit, "demandSource": demand_source,
            "capacity": None if capacity is None else round(capacity, 4),
            "capacityUnit": capacity_unit, "capacitySource": capacity_source,
            "capacitySourceKind": kind, "capacityBound": bound,
            "margin": None if m is None else round(m, 4), "verdict": verdict,
            # ONLY ON THE ROWS THAT NEED IT. Every margin knows its experiment, but repeating a
            # 300-character sentence on all 3888 of them put 2 MB of duplicated prose in the
            # report and buried the rows that are actually open. capacityGaps in the report
            # carries all three once, by load path, whatever each end's verdict came out as.
            "experimentThatWouldSettleIt": (experiment if verdict in ("UNSOURCED", "UNPROVEN")
                                            else None)}


