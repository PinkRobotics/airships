    # while P9 bracketed the other. The bearing probes run with ribs OFF (sampling.ribsForBearing
    # says so) and report 12 ends seating on 0.000 mm2; the part gen_nodes actually writes has
    # ribs = 3, and below the slot start — where the slot does not cut — the crest survives and
    # those same 12 ends land on 0.54 to 0.76 mm2 of rib shelf. Neither number is wrong; quoting
    # only one of them is. The ribless figure stays the headline because it is the shoulder the
