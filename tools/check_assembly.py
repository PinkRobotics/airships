def wrap_text(s, width=104, indent=" " * 6):
    words, lines, cur = s.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    lines.append(cur)
    return ("\n" + indent).join(lines)


def fit_overhang(elev_deg):
    """Fraction of a spigot's fit surface that overhangs steeper than 45 degrees.

    A cylinder lying at elevation theta on the bed presents an arc of its circumference below
    the 45 degree line: 1 - acos(-1/(sqrt2 cos theta))/pi, and nothing at all once the axis is
    steep enough that no generator crosses it.
    """
    c = math.cos(math.radians(elev_deg))
    x = -1.0 / (math.sqrt(2.0) * c) if abs(c) > 1e-9 else -1e9
    if x <= -1.0:
        return 0.0
    if x >= 1.0:
        return 1.0
    return 1.0 - math.acos(x) / math.pi


