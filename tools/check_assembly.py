def insertion_slack(e):
    """How much engagement this member-end could still gain before it cannot be assembled.

    ONE FORMULA AT EVERY END, because two would be two answers about one column. pilot_bound(P)
    is the deepest spigot a member dropped between two nodes already fixed in space can be
    rotated down onto, so bound - engagement is the headroom under it. At a CLOSING end that is
    the binding constraint and it is what the pilot spends: +1.21 mm on the long cut today. At
    a TREE end the far end is free, the member slides on along its own axis, and the same
    number is deeply negative and says nothing about that end's assembly — it is frozen anyway,
    because its two terms are the engagement and the cut length, and a change to either is a
    change to the insertion argument that has to be declared either way.
    """
    return round(e["pilotBoundMm"] - e["engagementMm"], 4)


