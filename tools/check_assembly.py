    max_seat = max(e["bearingAreaAt20umMm2"] for e in ends)
    n_max = sum(1 for e in ends if abs(e["bearingAreaAt20umMm2"] - max_seat) < 1e-6)
    # Corroboration, and it is a hard bound rather than a tolerance: a coplanar land cuts the
    # annulus at a FIXED azimuth, the same at every radius and every station, so no station may
    # exceed wrap x 28.2743 by more than the one azimuth cell the midpoint rule can round the
    # cut into. That slop is 28.2743/256 = 0.110 mm2 and it is why the rim ends measure 9.940
    # against an exact 9.838 (90 cells where 89.08 are owed) and 8.615 against 8.598.
    # Undershooting by more than a cell is the defect P6 reports; overshooting would mean the
    # midpoint integral or the exact wrap is wrong.
    # Per STATION, not per run: only stations 0 and 1 are sampled on BEAR_HI, and quoting its
    # 256-cell azimuth for the six stations that run on BEAR_LO's 128 was a bound half the size
    # of the one those stations are entitled to. It passed only because the worst overshoot,
    # 0.102 mm2 on a rim end, happened to land inside the tighter number.
    cell_slop = [math.pi * (25.0 - 16.0) / (BEAR_HI[1] if si < 2 else BEAR_LO[1])
                 for si in range(len(BEAR_DT))]
    sat_bad = [e["endId"] for e in ends
               if any(v > e["bearingAreaSatMm2"] + cell_slop[si]
                      for si, v in enumerate(e["bearingProfileMm2"]))]
    if sat_bad:
        bad.append(f"P6 corroboration: measured bearing area exceeds wrap x 28.2743 by more "
                   f"than one azimuth cell at {len(sat_bad)} ends (first {sat_bad[0]}) — the "
                   f"sampling or the exact wrap is wrong")
