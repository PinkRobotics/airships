def _tol_for(key):
    """One tolerance per property, and the ledger's own wherever the ledger has one."""
    return LEDGER_TOL.get(key, CONTRACT_TOL.get(key, DEFAULT_TOL))


def _moved(key, was, now):
    """Did this property move by more than its tolerance? Bools first — bool is an int."""
    if isinstance(was, list) and isinstance(now, list):
        return len(was) != len(now) or any(_moved(key, a, b) for a, b in zip(was, now))
    if isinstance(was, bool) or isinstance(now, bool):
        return was != now
    if isinstance(was, (int, float)) and isinstance(now, (int, float)):
        return abs(float(was) - float(now)) > _tol_for(key)
    return was != now                      # None against a number lands here, and should


def contract_drift(frozen, live):
    """Every proven property that moved, one row each, named by member-end and property."""
    rows = []

    def add(scope, ident, label, prop, was, now):
        rows.append({"scope": scope, "id": ident, "label": label, "property": prop,
                     "was": was, "now": now, "tolerance": _tol_for(prop)})

    if frozen.get("schemaVersion") != live["schemaVersion"]:
        # Not drift. The two files do not describe the same set of properties, so every row a
        # comparison produced would be an artefact of the schema change rather than a finding.
        add("contract", CONTRACT.name, "the file itself", "schemaVersion",
            frozen.get("schemaVersion"), live["schemaVersion"])
        return rows

    def walk(scope, ident, label, a, b, skip=()):
        for k in sorted(set(a) | set(b)):
            if k in skip:
                continue
            if k not in a:
                add(scope, ident, label, k, "ABSENT", b[k])
            elif k not in b:
                add(scope, ident, label, k, a[k], "ABSENT")
            elif _moved(k, a[k], b[k]):
                add(scope, ident, label, k, a[k], b[k])

    # The four scopes with one instance each carry no identifier: "param stub" and "metric
    # closingMembers" are already unambiguous, and "param paramsMm stub" is noise on every row.
    walk("param", "", "", frozen.get("paramsMm", {}), live["paramsMm"])
    walk("graph", "", "", frozen.get("graph", {}), live["graph"])
    walk("metric", "", "", frozen.get("metrics", {}), live["metrics"])
    for pid in sorted(set(frozen.get("checks", {})) | set(live["checks"])):
        a, b = frozen.get("checks", {}).get(pid), live["checks"].get(pid)
        if a is None or b is None:
            add("check", pid, "", "(the whole proof)",
                "ABSENT" if a is None else "PRESENT", "ABSENT" if b is None else "PRESENT")
            continue
        walk("check", pid, "", a, b)

    for scope, key, id_key in (("node", "nodes", "nodeIndex"), ("end", "ends", "endId")):
        was = {str(r[id_key]): r for r in frozen.get(key, [])}
        now = {str(r[id_key]): r for r in live[key]}
        for ident in sorted(set(was) | set(now)):
            a, b = was.get(ident), now.get(ident)
            if a is None or b is None:
                add(scope, ident, "", "(the whole record)",
                    "ABSENT" if a is None else "PRESENT", "ABSENT" if b is None else "PRESENT")
                continue
            label = (f"{b['role']}, {b['arms']} arms" if scope == "node" else
                     f"{b['role']}/{b['family']}, "
                     + ("closing" if b["isClosingMember"] else "tree"))
            walk(scope, ident, label, a, b, skip=("loadPaths",))
            pa, pb = a.get("loadPaths", {}), b.get("loadPaths", {})
            for path in sorted(set(pa) | set(pb)):
                if path not in pa or path not in pb:
                    add(scope, ident, label, f"loadPaths.{path}",
                        "ABSENT" if path not in pa else "PRESENT",
                        "ABSENT" if path not in pb else "PRESENT")
                    continue
                for f in sorted(set(pa[path]) | set(pb[path])):
                    if _moved(f, pa[path].get(f), pb[path].get(f)):
                        add(scope, ident, label, f"loadPaths.{path}.{f}",
                            pa[path].get(f), pb[path].get(f))
    return rows


def plural(n, one, many=None):
    """`1 proven property` and `4 proven properties`. A gate that cannot count reads careless."""
    return f"{n} {one if n == 1 else (many or one + 's')}"


def format_drift(rows, limit=40):
    """The drift as lines. Census first, because 432 rows of one property is one finding.

    THE ROWS ARE SAMPLED ACROSS PROPERTIES, not taken in order. Scopes are built in a fixed
    sequence — parameters, graph, metrics, proofs, the 51 nodes, then the 432 member-ends — so
    a plain head() spends the whole budget on whichever scope comes first and never reaches the
    member-end the reader came for. That happened the first time this ran: 32 node rows, six
    ends. One row per property in turn guarantees an example of everything that moved.
    """
    def show(v):
        return f"{v:.4f}".rstrip("0").rstrip(".") if isinstance(v, float) else repr(v)

    census = collections.Counter(r["property"] for r in rows)
    out = ["by property: " + ", ".join(f"{p} x{n}" for p, n in census.most_common())]
    queues, shown = [], []
    for r in rows:
        for q in queues:
            if q[0]["property"] == r["property"]:
                q.append(r)
                break
        else:
            queues.append([r])
    while queues and len(shown) < limit:
        for q in list(queues):
            if len(shown) >= limit:
                break
            shown.append(q.pop(0))
            if not q:
                queues.remove(q)
    for r in shown:
        moved = ""
        if isinstance(r["was"], (int, float)) and isinstance(r["now"], (int, float)) \
                and not isinstance(r["was"], bool) and not isinstance(r["now"], bool):
            moved = (f" (moved {float(r['now']) - float(r['was']):+.4f}, "
                     f"tolerance {r['tolerance']:g})")
        where = " ".join(x for x in (r["scope"], r["id"]) if x)
        where += f" ({r['label']})" if r["label"] else ""
        out.append(f"{where} {r['property']}: frozen {show(r['was'])}, "
                   f"now {show(r['now'])}{moved}")
    if len(rows) > limit:
        out.append(f"... and {len(rows) - limit} more rows — every one of them is in the "
                   f"report under contract.drift")
    return out


def contract_line(contract, frozen, drift, froze):
    """One sentence on the cap, printed on every run so its absence is as visible as its state.

    A gate you cannot see is a gate nobody trusts. This says how much is capped, when it was
    capped, and whether the article still matches it — in the same paragraph as the ledger,
    which is the other standing bill this run carries.
    """
    n = f"{len(contract['ends'])} member-ends and {len(contract['nodes'])} nodes"
    if froze:
        return (f"contract: REWRITTEN this run by --freeze. {n} are now capped at schema "
                f"{CONTRACT_SCHEMA} in {CONTRACT}, at the values measured above.")
    if frozen is None:
        return (f"contract: NONE on disk. {n} were measured and none of them is capped — "
                f"`python3 tools/check_assembly.py --freeze` is what starts the cap.")
    if drift:
        return (f"contract: BROKEN — {len(drift)} properties moved against the "
                f"{frozen.get('frozenAtUtc', 'undated')} freeze; the rows are at the top of "
                f"this run and in the report under contract.drift.")
    return (f"contract: {n} match {CONTRACT} exactly (schema "
            f"{frozen.get('schemaVersion')}, frozen {frozen.get('frozenAtUtc', 'undated')} in "
            f"{frozen.get('frozenInMode', 'an unrecorded')} mode). Nothing about these "
            f"connections has changed since it was capped.")


def check_note_figures(path, rows):
    """Hold a published sentence to the figure this run measured.

    WHY THIS IS HERE AND NOT IN check_analysis.py. That gate compares research/analysis/*.md
    against research/analysis/*.json, and not one of the figures below is produced by
    vacuum-cell.py — they are the prover's own measurements, and the only file that knows them
    is this one. Same arrangement as the VERIFICATION-PLAN.md mass check above, for the same
    reason: a published number is held by whatever generated it.

    A ROW WHOSE SENTENCE HAS GONE FAILS AS LOUDLY AS A WRONG NUMBER. `figures.json` taught this
    repository that the worst gate is the one that quietly stops finding its subject and prints
    a success line anyway, so a pattern that no longer matches is a failure and not a skip.
    """
    if not path.exists():
        return [f"prose drift: {path} is missing — {len(rows)} published joint figures have "
                f"nothing holding them"]
    # Whitespace collapsed first, so the patterns are anchored to the SENTENCE and not to where
    # a paragraph happens to wrap. Reflowing prose is not a change to a figure and must not
    # break a gate; changing the figure, or deleting the claim, still does.
    text = re.sub(r"\s+", " ", path.read_text())
    out = []
    for what, pattern, value, fmt in rows:
        hits = re.findall(pattern, text)
        want = format(value, fmt)
        if not hits:
            out.append(f"prose drift: {path.name} no longer contains the sentence that states "
                       f"{what} (pattern {pattern!r}) — the gate cannot see the figure it is "
                       f"supposed to hold, so the figure is not gated at all")
        elif any(h != want for h in hits):
            out.append(f"prose drift: {path.name} says {what} is "
                       f"{', '.join(sorted(set(hits)))} and this run measures {want} — fix the "
                       f"sentence, not this gate")
    return out


def read_contract():
    """The frozen contract, or a complaint that stands in for it."""
    if not CONTRACT.exists():
        return None, (f"no frozen contract at {CONTRACT} — the connections are measured but "
                      f"nothing is capping them. Read this run, then freeze it on purpose "
                      f"with `python3 tools/check_assembly.py --freeze`.")
    try:
        return json.loads(CONTRACT.read_text()), None
    except json.JSONDecodeError as exc:
        return None, (f"{CONTRACT} is not readable JSON ({exc}) — a contract that cannot be "
                      f"parsed caps nothing. Restore it from git or re-freeze deliberately.")


def contract_coverage(frozen, g, topo, manifest, prm):
    """Does the cap on disk describe THIS article at all? The cheap half of the gate.

    THE FAILURE THE PROPERTY DIFF CANNOT REPORT. A diff needs two comparable files: no
    contract, another prover's schema, or a contract frozen for a different graph produces
    either silence or 432 meaningless rows. This asks the graph, the slot rule and the
    manifest and evaluates no field at all, so it answers in a tenth of a second — which is
    why `make check` can ask it before it spends the two minutes on the measurement.
    """
    bad = []
    if frozen.get("schemaVersion") != CONTRACT_SCHEMA:
        bad.append(f"contract schemaVersion {frozen.get('schemaVersion')} against this "
                   f"prover's {CONTRACT_SCHEMA} — the two files do not describe the same "
                   f"properties, so re-freeze deliberately after reading what changed")
        return bad                       # nothing below is comparable across a schema change
    want_ends = {f"n{ni:02d}.a{ai:02d}"
                 for ni, (u, _r) in enumerate(g["nodes"])
                 for ai in range(len(g["info"][u]["dirs"]))}
    got_ends = {r["endId"] for r in frozen.get("ends", [])}
    if got_ends != want_ends:
        missing, extra = sorted(want_ends - got_ends), sorted(got_ends - want_ends)
        bad.append(f"the contract covers {len(got_ends)} member-ends and this article has "
                   f"{len(want_ends)}: {len(missing)} uncapped"
                   + (f" (first {missing[0]})" if missing else "")
                   + f", {len(extra)} capped and gone"
                   + (f" (first {extra[0]})" if extra else ""))
    if len(frozen.get("nodes", [])) != topo["V"]:
        bad.append(f"the contract covers {len(frozen.get('nodes', []))} nodes and this article "
                   f"has {topo['V']}")
    for k, want in (("V", topo["V"]), ("E", topo["E"]), ("cycleRank", topo["cycleRank"])):
        got = frozen.get("graph", {}).get(k)
        if got != want:
            bad.append(f"the contract was frozen on a graph with {k} = {got}; this one has "
                       f"{want} — it is capping another article")
    # The parameters the contract was frozen at against the ones the STLs on disk were cut for.
    # Every dimension in the cap is downstream of these, so a mismatch means the cap and the
    # part disagree before a single property has been compared.
    froz = frozen.get("paramsMm", {})
    for k in sorted(set(froz) | set(prm)):
        if k not in froz or k not in prm or _moved(k, froz[k], prm[k]):
            bad.append(f"parameter {k}: contract {froz.get(k, 'ABSENT')}, "
                       f"{'manifest' if manifest else 'defaults'} {prm.get(k, 'ABSENT')}")
    return bad


