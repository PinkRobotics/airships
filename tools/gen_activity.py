def render(days: list[dict]) -> tuple[str, str]:
    top = best(days)
    body = {
        "what": "Working hulls per captured day, measured on the page's own allocation "
                "of that day's published record. The default view opens on the day with "
                "the most working hulls (app/feeds.js bestReplayDay; ties to the newest "
                "date).",
        "tool": "tools/gen_activity.py",
        "measure": "hulls with a feasible plan after the page's allocator replays the "
                   "day (?day=DATE&seed=7, still air, no satellite heat)",
        "defaultDay": top,
        "days": days,
    }
    text = json.dumps(body, indent=1, ensure_ascii=False) + "\n"

    sources = ["data/season/2026.days.json"]
    for d in days:
        sources += [f"data/season/days/{d['date']}/fires.json",
                    f"data/season/days/{d['date']}/perims.json"]
    prov = {
        "file": "2026.activity.json",
        "kind": "file",
        "decision": "redistributed",
        "publisher": "Pink Robotics",
        "authorship": "Project-generated measurement of the simulated fleet; the season "
                      "files it reads stay under OGL-BC in their own records.",
        "description": "Working hulls per captured day of the 2026 season, measured by "
                       "the page's own allocator over each day's published record. The "
                       "default view opens on the day with the most working hulls; this "
                       "file is that ranking, as data. This sidecar covers that file.",
        "generator": "tools/gen_activity.py",
        "licence": "Apache-2.0",
        "licenceUrl": "LICENSE",
        "licenceStatement": "Apache License, Version 2.0",
        "licenceEvidence": "LICENSE; working-hull counts produced by the project's own "
                           "page simulation over committed season files.",
        "licenceReason": "Project-generated measurement of the simulated fleet, "
                         "describing no new fact of any real fire.",
        "attribution": "Pink Robotics. Licensed under Apache-2.0.",
        "source": sources,
        "sourcesSha256": {s: hashlib.sha256((ROOT / s).read_bytes()).hexdigest()
                          for s in sources},
        "ranking": {
            "days": len(days),
            "best": {"date": top, "working": next(d["working"] for d in days if d["date"] == top)},
            "measure": "hulls with a feasible plan after the page's allocator replays "
                       "the day (?day=DATE&seed=7, still air, no satellite heat)",
            "ties": "newest date",
        },
        "notes": "Regenerate with: python3 tools/gen_activity.py (no network); make "
                 "activitycheck regenerates and diffs. Each captured day is loaded the "
                 "way a visitor loads it and the page's own allocator runs over that "
                 "day's published record; the count is the hulls left with a feasible "
                 "plan; ties go to the newest date. The file carries no timestamp and no "
                 "environment facts on purpose: it must regenerate byte for byte on any "
                 "machine. It describes the simulated fleet, never a real fire, and adds "
                 "no fact to the season record.",
        "sha256": hashlib.sha256(text.encode()).hexdigest(),
        "measurements": {"bytes": len(text.encode())},
        "documentation": {"DATA-SOURCES.md": DOC_SOURCES, "data/README.md": DOC_README},
    }
    prov_text = json.dumps(prov, indent=2, ensure_ascii=False) + "\n"
    return text, prov_text


def main() -> None:
    days = all_days()
    if not days:
        raise SystemExit("gen_activity: no days in the season index; nothing to rank")
    with serve_tree(ROOT) as base:
        measured = []
        for d in days:
            rec = measure(base, d)
            measured.append({"date": d, "fires": rec["fires"], "working": rec["working"],
                             "standby": rec["standby"], "uncovered": rec["uncovered"]})
    text, prov_text = render(measured)
    if CHECK:
        for path, want in ((OUT, text), (PROV, prov_text)):
            have = path.read_text() if path.exists() else ""
            if have != want:
                sys.stderr.write(f"gen_activity --check: {path.name} drifts from a fresh "
                                 "measurement\n")
                sys.exit(1)
        tally = ", ".join(f"{d['date']}={d['working']}" for d in measured)
        print(f"activity: {len(measured)} captured days match the committed ranking ({tally}); "
              f"default {best(measured)}")
        return
    OUT.write_text(text)
    PROV.write_text(prov_text)
    print(f"activity: wrote {OUT} and {PROV.name} — " +
          ", ".join(f"{d['date']}={d['working']}" for d in measured) +
          f"; default {best(measured)}")


if __name__ == "__main__":
    main()
