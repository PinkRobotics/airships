#!/usr/bin/env python3
"""Working hulls per captured day, measured by the page's own simulation.

    tools/gen_activity.py            write data/season/2026.activity.json (+ its sidecar)
    tools/gen_activity.py --check    regenerate into memory and diff; exit 1 on any drift

Every captured day is a fleet day now — the no-fleet guard was removed on 2026-10-14 by
operator ruling — and the page's default view opens on the day with the most hulls
working: the busiest day of the peak August week the ruling names as the example.
"Most hulls working" is not an opinion held in this file: each captured day is loaded
the way a visitor loads it (?day=DATE, still air, no satellite heat — exactly what a
dated view runs), the page's own allocator runs over that day's published record, and
the count is the hulls left with a feasible plan (S.missions where !idle). Ties go to
the newest date, so the ranking can never prefer an older day for looking quieter.

Both files carry no timestamp and no environment facts on purpose: they must regenerate
byte for byte on any machine, and `--check` (make activitycheck) holds that.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from serve import serve_tree

OUT = ROOT / "data" / "season" / "2026.activity.json"
PROV = ROOT / "data" / "season" / "2026.activity.prov.json"
CHECK = "--check" in sys.argv

# What one day's page is asked after it has booted. Navigation time is not proof the
# plans have settled; the page's own readiness gates are.
PROBE = r"""
(async () => {
  const deadline = performance.now() + 300000;
  while (!(window.AIRSHIPS?.app?.ready)) {
    if (performance.now() >= deadline) return JSON.stringify({error: 'readiness deadline exceeded'});
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  const S = window.AIRSHIPS.app;
  while (!S.planning || S.planning.state !== 'settled') {
    if (performance.now() >= deadline) return JSON.stringify({error: 'planning deadline exceeded'});
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  const ov = document.getElementById('introOv'); if (ov && !ov.hidden) ov.click();
  return JSON.stringify({
    url: location.search, day: S.day, daySource: S.daySource, recordOnly: !!S.recordOnly,
    fires: S.fires.length,
    missions: S.missions.length,
    working: S.missions.filter(m => !m.idle).length,
    standby: S.standby.length,
    uncovered: S.uncovered,
  });
})()
"""


def all_days() -> list[str]:
    """Every captured day in the season index, ascending. The page's day control
    offers exactly these; the ranking measures exactly these."""
    days = json.loads((ROOT / "data/season/2026.days.json").read_text())["days"]
    return sorted(d["date"] for d in days)


def measure(base: str, date: str) -> dict:
    with tempfile.TemporaryDirectory(dir=os.environ.get("AIRSHIPS_TMPDIR") or None) as tmp:
        js = pathlib.Path(tmp) / "probe.js"
        js.write_text(PROBE)
        out = pathlib.Path(tmp) / "out.json"
        env = dict(os.environ, AIRSHIPS_TMPDIR=tmp, A3D_WINDOW="1440,900")
        r = subprocess.run(
            [sys.executable, str(ROOT / "tools" / "js_eval.py"),
             f"{base}index.html?day={date}&seed=7", str(js), str(out), "12"],
            capture_output=True, text=True, errors="replace", cwd=str(ROOT), env=env, timeout=420)
        if r.returncode != 0 or not out.exists():
            raise SystemExit(f"gen_activity: could not read the day {date}\n"
                             + r.stdout[-1500:] + r.stderr[-1500:])
        rec = json.loads(out.read_text())
    if rec.get("error"):
        raise SystemExit(f"gen_activity: {date}: {rec['error']}")
    if rec.get("day") != date or rec.get("daySource") != "day":
        raise SystemExit(f"gen_activity: {date}: the page did not settle on that day "
                         f"({rec.get('day')!r} via {rec.get('daySource')!r})")
    if rec.get("recordOnly"):
        raise SystemExit(f"gen_activity: {date} measured record-only; a captured day "
                         "must carry a fleet")
    return rec


def best(days: list[dict]) -> str:
    """Most working hulls; ties to the newest date."""
    return max(days, key=lambda d: (d["working"], d["date"]))["date"]


