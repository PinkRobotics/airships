def write_capture(folder, captured, incidents, perimeters, complete=True, said=None):
    """A capture folder as the generator expects one: pages, layer descriptions, a manifest."""
    folder.mkdir(parents=True)
    layer = json.dumps({"dateFieldsTimeReference": {"timeZone": "UTC"},
                        "editingInfo": {"dataLastEditDate": ms(captured) - 60000}}).encode()
    half = len(incidents) // 2      # two pages, so that paging is exercised
    files = {
        "incidents.layer.json": layer, "perimeters.layer.json": layer,
        "incidents.page-000.geojson": json.dumps({"features": incidents[:half]}).encode(),
        "incidents.page-001.geojson": json.dumps({"features": incidents[half:]}).encode(),
        "perimeters.page-000.geojson": json.dumps({"features": perimeters}).encode()}
    for name, data in files.items():
        (folder / name).write_bytes(data)

    def by_status(features):
        return count(f["properties"]["FIRE_STATUS"] for f in features)

    manifest = {
        "capturedAt": captured, "localDate": said or season.local_date(ms(captured)),
        "layers": {
            "incidents": {"url": INC_URL, "where": "1=1", "countOnly": len(incidents),
                          "byStatus": by_status(incidents), "complete": complete},
            "perimeters": {"url": PER_URL, "where": "1=1", "countOnly": len(perimeters),
                           "byStatus": by_status(perimeters), "complete": True}},
        "requests": [{"file": name, "url": "https://example.invalid/" + name, "bytes": len(data),
                      "sha256": hashlib.sha256(data).hexdigest()} for name, data in files.items()]}
    (folder / "MANIFEST.json").write_text(json.dumps(manifest))


def mirror_fire(number, status, size, ignition):
    props = {"FIRE_NUMBER": number, "FIRE_STATUS": status, "FIRE_CAUSE": "Lightning",
             "INCIDENT_NAME": number, "GEOGRAPHIC_DESCRIPTION": "Somewhere ", "CURRENT_SIZE": size,
             "IGNITION_DATE": ms(ignition), "FIRE_URL": "https://example.invalid/",
             "FIRE_OF_NOTE_IND": "N", "RESPONSE_TYPE_DESC": "Full"}
    return {"type": "Feature", "geometry": {"type": "Point", "coordinates": [-120.1, 50.9]},
            "properties": props}


def mirror_perim(number, status):
    return {"type": "Feature",
            "geometry": {"type": "Polygon",
                         "coordinates": [[[-120, 50], [-120, 50.1], [-119.9, 50], [-120, 50]]]},
            "properties": {"FIRE_NUMBER": number, "FIRE_STATUS": status,
                           "FIRE_SIZE_HECTARES": 3.5, "TRACK_DATE": ms("2019-07-06T00:00:00Z")}}


def write_mirror(folder, copies):
    """copies: (name, fetchedAt, features), each written the way pipeline/live.py writes."""
    folder.mkdir(parents=True)
    index = []
    for name, fetched, features in copies:
        sub = fetched.replace("-", "").replace(":", "")
        source = {"fires": season.FIRES_SOURCE, "perims": season.PERIMS_SOURCE}.get(name, "heat")
        data = json.dumps({"fetchedAt": fetched, "source": source,
                           "data": {"type": "FeatureCollection", "crs": season.CRS,
                                    "features": features}}, separators=(",", ":")).encode()
        (folder / sub).mkdir(exist_ok=True)
        (folder / sub / f"{name}.json").write_bytes(data)
        index.append({"name": name, "fetchedAt": fetched, "folder": sub, "file": f"{name}.json",
                      "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    (folder / "INDEX.json").write_text(json.dumps({"source": "synthetic", "copies": index}))


