@test
def hindsight_cannot_reach_the_dispatch_model_by_accident():
    """The season file is not something the page's feed code can swallow, and its one size
    goes by a name that nothing in the page or the model reads."""
    s = load(f"{YEAR}.json")
    assert s["notes"][0].startswith("HINDSIGHT."), "the first note must say hindsight"
    assert "dispatch model" in s["notes"][0], "the first note must name the dispatch model"
    for f in s["fires"]:
        same(list(f), RECORD_KEYS, f"{f['fire']} keys")
    sizes = [k for k in RECORD_KEYS if "size" in k.lower() or k.lower().endswith("ha")]
    same(sizes, ["hindsightSizeHa"], "size-like keys in a fire record")
    assert "hindsight" in s["fields"]["hindsightSizeHa"].lower(), "the field's own definition"
    same(sorted(s["fields"]), sorted(RECORD_KEYS), "documented fields")

    def keys(o):
        if isinstance(o, dict):
            for k, v in o.items():
                yield k
                yield from keys(v)
        elif isinstance(o, list):
            for v in o:
                yield from keys(v)

    # The names a size travels under on its way to the model. If either file stops using its
    # name, this guard is guarding the wrong word and must be looked at again.
    assert "CURRENT_SIZE" in (ROOT / "app" / "feeds.js").read_text(), (
        "app/feeds.js no longer reads a size from CURRENT_SIZE: revisit this guard")
    assert "sizeHa" in (ROOT / "sim" / "assign.js").read_text(), (
        "sim/assign.js no longer reads sizeHa: revisit this guard")
    used = set(keys(s))
    for name in ("sizeHa", "CURRENT_SIZE", "FIRE_SIZE_HECTARES", "size", "features", "data",
                 "fetchedAt", "properties"):
        assert name not in used, f"the season file has a key named {name!r}"
    return "one size, named hindsightSizeHa; no key the page or the model reads a size from"


def live_feeds():
    """ARC and FEEDS out of pipeline/live.py, with the wind grid the wind feed's address is
    built from: those five assignments are evaluated on their own, with `str` as the only
    builtin. The fetcher is not imported and nothing else in it runs."""
    tree = ast.parse((ROOT / "pipeline" / "live.py").read_text())
    names = (["WIND_LATS"], ["WIND_LONS"], ["WIND_POINTS"], ["ARC"], ["FEEDS"])
    wanted = [node for node in tree.body if isinstance(node, ast.Assign)
              and [getattr(t, "id", None) for t in node.targets] in names]
    same(len(wanted), 5, "the ARC, FEEDS and wind-grid assignments in pipeline/live.py")
    # One dictionary for globals and locals: a comprehension's inner scope reads globals.
    scope = {"__builtins__": {"str": str}}
    exec(compile(ast.Module(wanted, []), "pipeline/live.py", "exec"), scope)
    return scope["FEEDS"]


