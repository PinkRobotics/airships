"""The season gate: fresh files, pinned totals, and a date policy that does what it says.

    tests/season/check.py                                   everything that needs no raw inputs
    SEASON_CAPTURE=<capture folder> tests/season/check.py   and a regeneration from the raw inputs
    tests/season/check.py <word>                            only the tests whose name has the word

Three tiers. The first two run anywhere.

1. THE COMMITTED FILES. data/season/ is generated by pipeline/season.py from raw copies that
   run to megabytes and are deliberately not in this repository. So the freshness check
   rebuilds everything that CAN be rebuilt from committed files (every derived field of every
   fire, the summary, the day index, the provenance record, the snapshot day) and compares
   bytes. Then every published number is worked out a second time, by code written here and
   not shared with the generator: a generator checked only against itself proves nothing
   about its arithmetic. PINS below are the totals a reader will see published, and two
   fingerprints of the values that came straight from the raw inputs. They move only when
   somebody moves them. The documents that quote the numbers are held to the same data.

2. A SYNTHETIC SEASON. Sixteen invented fires, a recovered mirror history, a snapshot and
   three captures are written to scratch and run through the real generator. Every flag, both
   placement rules, the last copy of a local day across a UTC midnight, the status filter,
   --through, and every refusal are asserted there, on inputs small enough to check by hand.

3. THE RAW INPUTS. With SEASON_CAPTURE set, the season is regenerated from the capture and
   must match the committed files byte for byte, and the perimeter generalisation is held
   against every perimeter the server itself generalised. Without it those tests SKIP, loudly,
   naming the folders they need. They never pass quietly.

Exit status is non-zero on any failure. A skip is not a failure and is never silent.
Python 3 and its standard library; no browser, no node, no network.
"""
