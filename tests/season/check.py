@test
def synthetic_the_gate_notices():
    """Mutations. Each is something a hand or a bad merge could do to the committed files."""
    with scratch() as tmp:
        tmp = pathlib.Path(tmp)
        capture, snapshot = synthetic_world(tmp)
        out = tmp / "out"
        season.write(season.build(season.read_raw(capture, None, snapshot)), SYN, out)

        def gate():
            try:
                return season.drift(season.build(season.read_committed(SYN, out, snapshot)),
                                    SYN, out)
            except season.SeasonError as e:
                return [str(e)]

        same(gate(), [], "untouched")
        caught = []

        def mutate(name, old, new, expect):
            path = out / name
            original = path.read_bytes()
            assert original.count(old) >= 1, f"mutation target {old!r} is not in {name}"
            path.write_bytes(original.replace(old, new, 1))
            problems = gate()
            path.write_bytes(original)
            assert any(expect in p for p in problems), f"{name} {old!r}: not noticed ({problems})"
            caught.append(name)

        # a published value changed by hand: what is derived from it no longer follows
        mutate(f"{SYN}.json", b'"hindsightSizeHa":0.5', b'"hindsightSizeHa":5.5', "summary.json")
        mutate(f"{SYN}.json", b'"ignitionMs":1562011200000', b'"ignitionMs":1562097600000',
               f"{SYN}.json")
        # a published value that nothing is derived from: the provenance's sha256 notices
        mutate(f"{SYN}.json", b'"name":"K10001"', b'"name":"K1000X"', "prov.json")
        # a derived value changed by hand
