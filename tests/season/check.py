@test
def published_facts_recomputed_a_second_way():
    """Every number in the summary, worked out again here from the records and the day files."""
    s, summary = load(f"{YEAR}.json"), load(f"{YEAR}.summary.json")
    fires = s["fires"]
    by_number = {f["fire"]: f for f in fires}
    tally = count(f["statusAtCapture"] for f in fires)
    same(tally, summary["statusAtCapture"], "status tally")
    same(sum(1 for f in fires if f["statusAtCapture"] != "Out"), summary["notOutAtCapture"],
         "not out at capture")

    small = [f for f in fires if f["hindsightSizeHa"] is not None and f["hindsightSizeHa"] < 1]
    same({"fires": len(small), "out": sum(1 for f in small if f["statusAtCapture"] == "Out"),
          "notOut": sum(1 for f in small if f["statusAtCapture"] != "Out"),
          "sizeZero": sum(1 for f in fires if f["hindsightSizeHa"] == 0),
          "sizeUnknown": sum(1 for f in fires if f["hindsightSizeHa"] is None)},
         summary["under1ha"], "under 1 ha")
    same(len(small), PINS["under1ha"], "under 1 ha (pin)")

    # the median: exact instants, over the fires that are out and whose dates are possible
    spans = [(f["outMs"] - f["ignitionMs"]) / 86400000 for f in fires
             if f["dates"]["ok"] and f["outMs"] is not None]
    same({"medianDays": round(median(spans), 2), "medianHours": round(median(spans) * 24, 1),
          "fires": len(spans), "outFiresLeftOut": tally["Out"] - len(spans)},
         summary["ignitionToOut"], "ignition to out")
    same(summary["ignitionToOut"]["medianDays"], PINS["medianDaysIgnitionToOut"], "median (pin)")

    for key, field in (("byCause", "cause"), ("byCentre", "centre")):
        same(count(f[field] for f in fires), summary[key], key)
        same(summary[key], PINS[key], f"{key} (pin)")
    for f in fires:                       # the centre name is the number's letter, every time
        same(f["centre"], LETTERS[f["fire"][0]], f"{f['fire']} centre")
    same({"atCapture": sum(1 for f in fires if f["fireOfNote"]),
          "atCaptureOrEarlier": sum(1 for f in fires if f["fireOfNote"] or f["wasFireOfNote"])},
         summary["fireOfNote"], "fires of note")

    # the timeline, by brute force: one question per fire per day
    t = summary["timeline"]
    same(t["to"], s["capture"]["localDate"], "timeline end")
    same(t["from"], min(f["ignited"] for f in fires if f["ignited"]), "timeline start")
    day, last = datetime.date.fromisoformat(t["from"]), datetime.date.fromisoformat(t["to"])
    series = []
    while day <= last:
        d = day.isoformat()
        series.append({
            "date": d,
            "started": sum(1 for f in fires if f["ignited"] == d),
            "out": sum(1 for f in fires if f["out"] == d),
            "active": sum(1 for f in fires if f["ignited"] is not None and f["ignited"] <= d
                          and (f["out"] is None or d < f["out"]))})
        day += datetime.timedelta(days=1)
    same(series, t["days"], "timeline days")
    top = max(x["active"] for x in series)
    same({"active": top, "dates": [x["date"] for x in series if x["active"] == top]}, t["peak"],
         "peak day")
    same(t["peak"], PINS["peak"], "peak day (pin)")
    same(sum(x["started"] for x in series), t["firesOnTimeline"], "fires started on the timeline")
    same(t["firesOnTimeline"] + t["firesNotOnTimeline"], len(fires), "timeline split")
    running = 0
    for x in series:                     # started minus out, accumulated, IS active
        running += x["started"] - x["out"]
        same(running, x["active"], f"running balance on {x['date']}")

    # how closely the numbering follows the calendar
    ok = [datetime.date.fromisoformat(f["ignited"]) for f in fires if f["dates"]["ok"]]
    gaps = [abs((b - a).days) for a, b in zip(ok, ok[1:])]
    same({"firesWithPossibleDates": len(ok), "pairs": len(gaps),
          "ignitedTheSameDay": sum(1 for g in gaps if g == 0),
          "ignitedWithinOneDay": sum(1 for g in gaps if g <= 1),
          "ignitedWithinSevenDays": sum(1 for g in gaps if g <= 7), "largestGapDays": max(gaps)},
         summary["numbering"], "numbering")

    # the status days, recounted from the day files themselves
    listed_ever, first_seen = set(), {}
    for want in summary["statusDays"]["days"]:
        doc = load(f"days/{want['date']}/fires.json")
        props = [f["properties"] for f in doc["data"]["features"]]
        when = season.parse_utc(doc["fetchedAt"])
        same(local_day(when), want["date"], "a status day's local date")
        listed = {p["FIRE_NUMBER"] for p in props}
        listed_ever |= listed
        for p in props:
            first_seen.setdefault(p["FIRE_NUMBER"], p["IGNITION_DATE"])
        burning = {f["fire"] for f in fires if f["dates"]["ok"] and f["ignitionMs"] <= when
                   and (f["outMs"] is None or f["outMs"] > when)}
        got = {
            "date": want["date"], "fetchedAt": doc["fetchedAt"], "fires": len(props),
            "byStatus": count(p["FIRE_STATUS"] for p in props),
            "byCause": count(p["FIRE_CAUSE"] for p in props),
            "byCentre": count(LETTERS[p["FIRE_NUMBER"][0]] for p in props),
            "under1ha": sum(1 for p in props
                            if p["CURRENT_SIZE"] is not None and p["CURRENT_SIZE"] < 1),
            "fireOfNote": sum(1 for p in props if p["FIRE_STATUS"] == "Fire of Note"
                              or p["FIRE_OF_NOTE_IND"] in ("Y", "Yes")),
            "perimeters": len(load(f"days/{want['date']}/perims.json")["data"]["features"]),
            "hindsightAtThatMoment": {
                "burning": len(burning), "alsoListed": len(burning & listed),
                "notListed": len(burning - listed), "listedNotBurning": len(listed - burning)}}
        same(got, want, f"status day {want['date']}")
    same({"firesListedOnAStatusDay": len(listed_ever),
          "ofThemInSeasonFile": len(listed_ever & set(by_number)),
          "ofThemNotInSeasonFile": sorted(listed_ever - set(by_number)),
          "seasonFiresNeverListed": len(set(by_number) - listed_ever)},
         summary["coverage"], "coverage")

    # how far the ignition date moved between a fire's first status day and the capture
    shifts = [(by_number[n]["ignitionMs"] - then, by_number[n]["ignitionMs"], then)
              for n, then in first_seen.items() if n in by_number and then is not None
              and by_number[n]["ignitionMs"] is not None]
    moved = [d for d, _, _ in shifts if d]
    same({"firesCompared": len(shifts), "sameInstant": sum(1 for d, _, _ in shifts if d == 0),
          "earlierAtCapture": sum(1 for d, _, _ in shifts if d < 0),
          "laterAtCapture": sum(1 for d, _, _ in shifts if d > 0),
          "differentLocalDate": sum(1 for _, now, then in shifts
                                    if local_day(now) != local_day(then)),
          "medianShiftHoursWhereMoved": round(median(moved) / 3600000, 1) if moved else None},
         summary["ignitionRevised"], "ignition revised")
    return (f"under 1 ha {len(small):,}; median {round(median(spans), 2)} d over "
            f"{len(spans):,} fires; peak {top} on {', '.join(t['peak']['dates'])}; "
            f"{len(series)} timeline days; {len(summary['statusDays']['days'])} status days")


