    roots = b"|".join(re.escape(slash + name + slash) for name in (b"home", b"Users", b"root"))
    patterns = {
        "a home path": re.compile(roots + rb"|[A-Za-z]:\\+Users"),
        "an e-mail address": re.compile(rb"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}")}
