def quietly(args):
    """season.main() without its printed table."""
    keep = sys.stdout, sys.stderr
    with open(os.devnull, "w") as nowhere:
        sys.stdout = sys.stderr = nowhere
        try:
            return season.main([str(a) for a in args])
        finally:
            sys.stdout, sys.stderr = keep


def tree(folder):
    return {p.relative_to(folder).as_posix(): p.read_bytes()
            for p in folder.rglob("*") if p.is_file()}


