@test
def raw_generalisation_reproduces_the_servers():
    """A capture day's perimeters are generalised here; a mirror day's were generalised by the
    server. Where both hold one perimeter at one vintage, the vertices must be identical."""
    capture, mirror, _ = raw_inputs()
    full = {}
    for f in season.read_capture(capture)["perimeters"]["features"]:
        full.setdefault(f["properties"]["FIRE_NUMBER"], []).append(f)

    def compare(features):
        """(perimeters reproduced exactly, perimeters held at the capture's vintage)."""
        verdict = {}
        for f in features:
            p = f["properties"]
            held = full.get(p["FIRE_NUMBER"], [])
            vintage = (p["TRACK_DATE"], p["FIRE_SIZE_HECTARES"])
            if len(held) != 1 or vintage != (held[0]["properties"]["TRACK_DATE"],
                                             held[0]["properties"]["FIRE_SIZE_HECTARES"]):
                continue
            exact = season.generalise(held[0]["geometry"]) == f["geometry"]
            verdict[p["FIRE_NUMBER"]] = verdict.get(p["FIRE_NUMBER"], True) and exact
        return sum(verdict.values()), len(verdict)

    served = [f for _, doc in mirror_copies(mirror, "perims") for f in doc["data"]["features"]]
    exact, total = compare(served)
    same((exact, total), (PINS["generalisation"]["mirrorHistory"],) * 2,
         "perimeters reproduced exactly, of those held at the same vintage: mirror history")
    snap = json.loads((ROOT / "data" / "snapshot.json").read_bytes())["perimeters"]["features"]
    exact2, total2 = compare(snap)
    same((exact2, total2), (PINS["generalisation"]["snapshot"],) * 2,
         "perimeters reproduced exactly, of those held at the same vintage: snapshot")
    return (f"{exact} of {total} same-vintage perimeters in the mirror history and "
            f"{exact2} of {total2} in the snapshot: identical vertices")


@test
def raw_status_days_are_the_last_copy_of_each_local_day():
    """The selection, done again here from the recovered index without the generator's code."""
    capture, mirror, _ = raw_inputs()
    last, copies = {}, 0
    for c, _ in mirror_copies(mirror, "fires"):
        copies += 1
        when = datetime.datetime.fromisoformat(c["fetchedAt"].replace("Z", "+00:00"))
        day = when.astimezone(VANCOUVER).strftime("%Y-%m-%d")
        if day not in last or when > last[day][0]:
            last[day] = (when, c)
    index = load(f"{YEAR}.days.json")
    same(copies, index["mirrorHistory"]["fireCopies"], "fires copies in the recovered history")
    got = {d["date"]: (d["fetchedAt"], d["fires"]["sha256"]) for d in index["days"]
           if d["kind"] == "mirror-history"}
    want = {day: (when.strftime("%Y-%m-%dT%H:%M:%SZ"), c["sha256"])
            for day, (when, c) in last.items() if day not in got or got[day][1] == c["sha256"]}
    superseded = sorted(set(last) - set(want))
    for day in superseded:           # a later copy of another kind took the day; it must say so
        entry = [d for d in index["days"] if d["date"] == day][0]
        assert any(x["kind"] == "mirror-history" for x in entry["source"].get(
            "supersedes", [])), f"{day}: a recovered copy was passed over and nothing says so"
    same(got, want, "mirror days")
    for day in got:
        when, c = last[day]
        same((SEASON / "days" / day / "fires.json").read_bytes(),
             (mirror / c["folder"] / c["file"]).read_bytes(), f"{day} bytes")
    return (f"{copies} copies on {len(last)} local dates; {len(got)} status days are the last "
            f"copy of their date, byte-identical; {len(superseded)} superseded by a later kind")


