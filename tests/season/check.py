def raises(fn, fragment):
    try:
        fn()
    except season.SeasonError as e:
        assert fragment in str(e), f"refused for the wrong reason: {e}"
        return str(e)
    raise AssertionError(f"was not refused; expected an error mentioning {fragment!r}")


def load(name):
    return json.loads((SEASON / name).read_bytes())


def local_day(ms):
    """This file's own conversion of an instant to its Vancouver date, not the generator's."""
    d = datetime.datetime.fromtimestamp(ms / 1000, tz=datetime.timezone.utc)
    return d.astimezone(VANCOUVER).strftime("%Y-%m-%d")


def count(values):
    """How many of each. A missing value is counted under 'null', as the files publish it."""
    out = {}
    for v in values:
        key = "null" if v is None else v
        out[key] = out.get(key, 0) + 1
    return out


def median(values):
    values = sorted(values)
    mid = len(values) // 2
    return values[mid] if len(values) % 2 else (values[mid - 1] + values[mid]) / 2


def fingerprint(fires):
    """The season record with everything derived stripped out: what the capture itself said."""
    rows = [[f[k] for k in AS_PUBLISHED] for f in fires]
    return hashlib.sha256(json.dumps(rows, separators=(",", ":")).encode()).hexdigest()


def day_fingerprint(index, folder=SEASON):
    lines = []
    for d in index["days"]:
        for name in ("fires", "perims"):
            data = (folder / d[name]["file"]).read_bytes()
            lines.append(f"{d[name]['file']} {hashlib.sha256(data).hexdigest()}")
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()


def squeeze(text):
    return " ".join(text.split())


def long_date(iso):
    """2026-10-01 -> '1 October'."""
    return f"{int(iso[8:10])} {MONTHS[int(iso[5:7])]}"


def word(n):
    return NUMBER_WORDS[n] if 0 <= n < len(NUMBER_WORDS) else str(n)


