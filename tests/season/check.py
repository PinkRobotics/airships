@test
def status_days_carry_only_what_was_known_that_day():
    s, index = load(f"{YEAR}.json"), load(f"{YEAR}.days.json")
    by_number = {f["fire"]: f for f in s["fires"]}
    kinds, renumbered = {}, []
    for d in index["days"]:
        kinds[d["kind"]] = kinds.get(d["kind"], 0) + 1
        fires = load(d["fires"]["file"])["data"]["features"]
        if d["kind"] == "mirror-history":       # the recovered copy itself, byte for byte
            for name in ("fires", "perims"):
                same((d[name]["bytes"], d[name]["sha256"]),
                     (d["source"][name]["bytes"], d["source"][name]["sha256"]),
                     f"{d['date']} {name} against the recovered copy")
        elif d["kind"] == "repository-snapshot":   # data/snapshot.json, minus two properties
            same(d["source"]["file"], "data/snapshot.json", "the snapshot day's source")
            snap = json.loads((ROOT / d["source"]["file"]).read_bytes())
            for name, key in (("fires", "fires"), ("perims", "perimeters")):
                got = load(d[name]["file"])["data"]["features"]
                same(len(got), len(snap[key]["features"]), f"{d['date']} {name} count")
                for a, b in zip(got, snap[key]["features"]):
                    same(a["geometry"], b["geometry"], f"{d['date']} geometry")
                    same(a["properties"], {k: b["properties"][k] for k in a["properties"]},
                         f"{d['date']} properties")
        elif d["kind"] == "capture" and d["source"]["manifest"] == s["capture"]["manifest"]:
            # the season's own capture: that copy's fires that were not out, and no others
            want = {f["fire"]: (f["statusAtCapture"], f["hindsightSizeHa"], f["ignitionMs"])
                    for f in s["fires"] if f["statusAtCapture"] not in (None, "Out")}
            got = {f["properties"]["FIRE_NUMBER"]: (
                f["properties"]["FIRE_STATUS"], f["properties"]["CURRENT_SIZE"],
                f["properties"]["IGNITION_DATE"]) for f in fires}
            same(got, want, f"{d['date']} against the capture it came from")
        else:
            same(d["kind"], "capture", f"{d['date']}: an unknown kind of day")
        # A number the season file does not have is named, with the season fire that has its
        # sequence number. Where there is one, it is the same fire: same point, same ignition.
        strangers = sorted(f["properties"]["FIRE_NUMBER"] for f in fires
                           if f["properties"]["FIRE_NUMBER"] not in by_number)
        same([x["fire"] for x in d["notInSeasonFile"]], strangers, f"{d['date']} strangers")
        for x in d["notInSeasonFile"]:
            if x["sameSequenceNumberAs"] is None:
                continue
            now = by_number[x["sameSequenceNumberAs"]]
            then = [f for f in fires if f["properties"]["FIRE_NUMBER"] == x["fire"]][0]
            lon, lat = then["geometry"]["coordinates"]
            same((round(lat, 4), round(lon, 4), then["properties"]["IGNITION_DATE"]),
                 (now["lat"], now["lon"], now["ignitionMs"]),
                 f"{x['fire']} on {d['date']} and {now['fire']} in the season file")
            renumbered.append(f"{x['fire']} is {now['fire']}")
    same(sorted(kinds), sorted(index["kinds"]), "every kind of day the index defines is in use")
    # What a day knew is not what hindsight says. Had the days been cut from the season file
    # these would agree, so the disagreement is the proof that they were not.
    first = load(index["days"][0]["fires"]["file"])["data"]["features"]
    differ = sum(1 for f in first if f["properties"]["FIRE_NUMBER"] in by_number
                 and f["properties"]["CURRENT_SIZE"]
                 != by_number[f["properties"]["FIRE_NUMBER"]]["hindsightSizeHa"])
    assert differ > 0, "the first status day's sizes all equal hindsight: that cannot be right"
    return (f"{kinds.get('mirror-history', 0)} recovered copies, "
            f"{kinds.get('repository-snapshot', 0)} snapshot, {kinds.get('capture', 0)} capture; "
            f"{differ} of {len(first)} sizes on {index['days'][0]['date']} differ from "
            f"hindsight; renumbered: {', '.join(renumbered) or 'none'}")


